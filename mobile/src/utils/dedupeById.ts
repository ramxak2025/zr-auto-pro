/**
 * Схлопывает дубли по `id`, сохраняя порядок и ПЕРВОЕ вхождение.
 *
 * ЗАЧЕМ: страховка второго рубежа для бесконечных лент. Основную причину
 * дублей — offset-пагинацию по живой ленте — вылечил переход на курсор
 * (см. ChecksScreen), но список обязан оставаться корректным и при любом
 * будущем источнике страниц. Дубль `id` в FlatList — это дубль React-ключа:
 * ячейки начинают рисоваться не в свою позицию, отсюда «белые» и «чужие»
 * строки на экране.
 *
 * Первое вхождение, а не последнее: страницы идут сверху вниз (свежие →
 * старые), и если одна и та же строка попала в две страницы, верная её
 * позиция — верхняя.
 */
export function dedupeById<T extends { id: string }>(items: readonly T[]): T[] {
  const seen = new Set<string>();
  const out: T[] = [];
  for (const item of items) {
    const id = item?.id;
    if (typeof id !== 'string' || id.length === 0) {
      // Строка без id не участвует в дедупликации: выбрасывать её было бы
      // потерей данных, а «схлопывать» такие между собой — неверно.
      out.push(item);
      continue;
    }
    if (seen.has(id)) continue;
    seen.add(id);
    out.push(item);
  }
  return out;
}
