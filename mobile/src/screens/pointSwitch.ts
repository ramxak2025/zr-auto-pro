/**
 * МГНОВЕННАЯ СМЕНА ФИЛИАЛА — ЧИСТЫЕ ПРАВИЛА (167).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Ровно та же причина, что у второго шага входа
 * (loginPointSelection.ts): у переключения несколько отказов, и у каждого
 * РАЗНЫЙ правильный исход. Ошибка здесь стоит доступа и денег — либо человека
 * выкинет из живой сессии на пустом месте, либо он останется в старом филиале,
 * думая, что уже в новом, и пробьёт чек не в тот автосервис. «На глаз» такую
 * ветвистость не проверить, поэтому она живёт чистой функцией с тестами.
 *
 * ЧТО ТАКОЕ ПЕРЕКЛЮЧЕНИЕ. Это ПЕРЕВЫПУСК сессии, а не вход без пароля: личность
 * уже подтверждена живым токеном, сервер лишь проверяет право управления
 * персоналом и доступ к целевому филиалу, выдаёт новый токен и НЕМЕДЛЕННО гасит
 * старый. Значит:
 *   • прежний bearer мёртв сразу — grace-окна, как у /auth/refresh, здесь нет;
 *   • запросы, улетевшие ДО применения нового токена, вернут 401 «Токен
 *     отозван». Гасить из-за них сессию нельзя, и мобилка их и не видит: 401
 *     разлогинивает только при совпадении эпохи токена (см. api/axios.ts).
 *
 * ОСОБЫЙ СЛУЧАЙ — ПОТЕРЯННЫЙ ОТВЕТ. Если сервер переключение выполнил, а ответ
 * до телефона не доехал, старый токен уже мёртв, а новый клиент не получил.
 * Это НЕ тихая порча данных: следующий же запрос вернёт 401, и человек попадёт
 * на экран входа, где выберет филиал руками. Поэтому сетевой сбой честно
 * трактуется как «не переключились», а не как «попробуем догадаться».
 */
import { apiErrorMessage, apiErrorStatus } from '../../../shared/utils/apiError';

/** Что делать после неудачной попытки мгновенно сменить филиал. */
export type PointSwitchFailure = {
  /**
   * • `stay`    — остаться на месте, повтор законен (сеть, 5xx, rate-limit);
   * • `refresh` — остаться, но перезапросить список филиалов: сервер отказал
   *               по ПРАВИЛУ (нет права / филиал закрыли или отобрали), и
   *               показанный список уже может быть неправдой;
   * • `relogin` — сессия недействительна. Отдельного диалога НЕ показываем:
   *               перехватчик axios уже увёл человека на экран входа, и
   *               второе окно поверх него только напугало бы.
   */
  action: 'stay' | 'refresh' | 'relogin';
  /** Заголовок диалога — короткий и по делу. */
  title: string;
  /** Текст для человека. Сообщение сервера показываем ДОСЛОВНО, если оно есть. */
  message: string;
};

/**
 * Разбор отказа POST /auth/switch-point.
 *
 * Сообщение сервера всегда важнее своего: именно оно объясняет ПРИЧИНУ
 * («…доступно только руководителю, выйдите и войдите заново», «Филиал
 * недоступен») и говорит, что делать дальше. Придуманный нами текст в этом
 * месте только запутал бы.
 */
export function resolvePointSwitchFailure(err: unknown): PointSwitchFailure {
  const status = apiErrorStatus(err);
  const serverMessage = apiErrorMessage(err);

  // Ответа нет вовсе — сеть. Сессия цела (а если сервер всё же успел
  // переключить, первый же следующий запрос честно уведёт на вход).
  if (status === null) {
    return {
      action: 'stay',
      title: 'Нет связи с сервером',
      message: 'Филиал не переключён. Проверьте подключение и нажмите ещё раз.',
    };
  }

  // 401 — сессия действительно недействительна (токен отозван, аккаунт уволен
  // или деактивирован, пользователь не найден). Перехватчик axios уже погасил
  // её и увёл на вход: наше дело — не мешать.
  if (status === 401) {
    return {
      action: 'relogin',
      title: 'Войдите заново',
      message: serverMessage ?? 'Сессия больше не действительна. Войдите заново и выберите филиал.',
    };
  }

  // 403 — это ПРАВИЛО, а не сбой: нет права управления персоналом, филиал чужой
  // или закрыт, либо активен режим «войти как владелец». Сессию НЕ гасим,
  // список филиалов перезапрашиваем: он мог устареть ровно в этом месте.
  if (status === 403) {
    return {
      action: 'refresh',
      title: 'Не удалось перейти',
      message:
        serverMessage ??
        'Перейти в этот филиал нельзя. Чтобы работать в нём, выйдите из приложения и войдите заново, выбрав его в списке.',
    };
  }

  // 429 — общий write-бакет. Повтор законен, но не прямо сейчас.
  if (status === 429) {
    return {
      action: 'stay',
      title: 'Слишком часто',
      message: serverMessage ?? 'Слишком много запросов. Подождите минуту и попробуйте ещё раз.',
    };
  }

  // 400 — сюда попадает только испорченный запрос (филиал не UUID). Для
  // человека это тот же тупик, что и правило: обновляем список и остаёмся.
  if (status === 400) {
    return {
      action: 'refresh',
      title: 'Не удалось перейти',
      message: serverMessage ?? 'Филиал не найден. Обновите список и попробуйте ещё раз.',
    };
  }

  // 5xx и всё прочее: сервер жив, но сейчас не отвечает по делу. Сессия цела.
  return {
    action: 'stay',
    title: 'Ошибка сервера',
    message: serverMessage ?? `Сервер вернул код ${status}. Попробуйте ещё раз.`,
  };
}

/** «1 заказ-наряд» · «2 заказ-наряда» · «5 заказ-нарядов» (11–14 — тоже «-ов»). */
function orderNounRu(count: number): string {
  const tail = count % 100;
  const last = count % 10;
  if (tail >= 11 && tail <= 14) return 'заказ-нарядов';
  if (last === 1) return 'заказ-наряд';
  if (last >= 2 && last <= 4) return 'заказ-наряда';
  return 'заказ-нарядов';
}

/**
 * ЧТО ЧЕЛОВЕК ЧИТАЕТ ПЕРЕД ПЕРЕКЛЮЧЕНИЕМ, ЕСЛИ НА ТЕЛЕФОНЕ ЛЕЖАТ НЕОТПРАВЛЕННЫЕ
 * ЧЕКИ. Это деньги, а не черновики, и молча увозить их в другой автосервис
 * нельзя. Текст обязан ответить ровно на два вопроса: «что с ними будет» и
 * «куда они уйдут».
 *
 * Обещание «уйдут в <текущий филиал>» — не вежливость, а факт: перед сменой
 * сессии филиал прибивается к каждой записи очереди
 * (offlineCheckQueue.stampPendingPoint), поэтому досылка из новой сессии всё
 * равно попадёт в тот автосервис, где чек набивали.
 *
 * Пустая строка = очередь пуста: диалога быть не должно вовсе, переключение
 * делается сразу («просто нажал, переключился»).
 */
export function pendingChecksSwitchNotice(count: number, currentPointName: string | null): string {
  if (count <= 0) return '';
  const noun = orderNounRu(count);
  const adj = count % 10 === 1 && count % 100 !== 11 ? 'неотправленный' : 'неотправленных';
  const where = currentPointName ? `«${currentPointName}»` : 'текущий филиал';
  return (
    `На телефоне ${count} ${adj} ${noun} — они ещё не ушли на сервер. ` +
    `Сейчас попробуем отправить их в ${where}. ` +
    `Если связи нет, записи останутся на телефоне и всё равно уйдут в ${where}: филиал записан в каждой из них.`
  );
}
