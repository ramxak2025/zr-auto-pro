/**
 * pointsSwitchTarget — куда деть человека, когда он переходит в другой
 * автосервис из раздела «Филиалы» (мульти-точки 156/160/161), и когда его
 * сначала надо спросить.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Правило зависит от того, ЧТО лежит под «Филиалами» в
 * стеке навигации, а цена ошибки — потерянный заказ-наряд: состав чека живёт
 * ТОЛЬКО в памяти экрана Кассы, черновика на сервере нет. Такое правило обязано
 * быть чистой функцией с тестами, а не веткой внутри 660-строчного экрана.
 *
 * ОТКУДА ВЗЯЛАСЬ ЗАДАЧА. Индикатор автосервиса (components/PointIndicator)
 * стоит в том числе на Кассе и ведёт в «Филиалы». Экран создания заказ-наряда
 * (CheckCreate) живёт на КОРНЕВОМ стеке, поэтому любой уход с корня его
 * размонтирует. Кассир правил заказ-наряд, добавил три работы и две запчасти,
 * тронул строку с автосервисом «просто посмотреть» — и всё исчезло без вопроса.
 * Сам тап починен push'ем поверх (см. navigation/entityLinks.openPoints), а
 * здесь закрыт второй путь потери: кнопка «Перейти» внутри «Филиалов».
 */

/** Роут, лежащий в стеке ПОД «Филиалами», в том виде, в каком его отдаёт
 *  navigation.getState(). Всё опционально: состояние вложенного навигатора
 *  появляется только после его первой отрисовки. */
export interface RouteBelowPoints {
  name?: string;
  params?: { id?: string } | Record<string, unknown>;
  state?: {
    index?: number;
    routes?: { name?: string }[];
  };
}

/** Читает `params.id` независимо от того, как типизированы params роута. */
function checkIdParam(below: RouteBelowPoints): string | undefined {
  const id = (below.params as { id?: unknown } | undefined)?.id;
  return typeof id === 'string' && id.length > 0 ? id : undefined;
}

/**
 * Набирают ли прямо сейчас НОВЫЙ заказ-наряд на экране под «Филиалами».
 *
 * Касса существует в двух экземплярах, поэтому случая два:
 *   • `CheckCreate` на корневом стеке — приход из Записей, «+» с доски, правка
 *     чека из Журнала. Новым считается только тот, у которого нет `params.id`:
 *     он ещё никому не принадлежит и спокойно пробивается в только что
 *     выбранном автосервисе;
 *   • `Main` с активной вкладкой `NewCheck` — Касса как центральный таб.
 *
 * Это основной путь сюда: сервер отвечает «Выберите филиал, чтобы пробить
 * чек», человек идёт выбирать — и обязан вернуться к своему заказ-наряду, а не
 * найти пустую Кассу.
 */
export function isComposingNewCheckBelow(below: RouteBelowPoints | null | undefined): boolean {
  if (!below) return false;
  if (below.name === 'CheckCreate') return !checkIdParam(below);
  if (below.name === 'Main') {
    const tabs = below.state;
    const activeTab = tabs?.routes?.[tabs?.index ?? -1];
    return activeTab?.name === 'NewCheck';
  }
  return false;
}

/**
 * Под «Филиалами» открыта правка СУЩЕСТВУЮЩЕГО заказ-наряда.
 *
 * Такой чек принадлежит прежнему автосервису: после перехода его данные
 * оказываются вне области видимости, экран закроется, а несохранённые правки
 * пропадут. Вернуть человека на него, как в случае с новым чеком, нельзя —
 * значит, надо спросить до перехода, а не поставить перед фактом.
 */
export function needsCheckLossConfirm(below: RouteBelowPoints | null | undefined): boolean {
  return below?.name === 'CheckCreate' && !!checkIdParam(below);
}

/**
 * Куда уводить после успешного перехода в автосервис.
 *   • `back`      — вернуться на Кассу с набранным заказ-нарядом;
 *   • `dashboard` — на главную, как было всегда: переключение сбрасывает весь
 *                   кеш, и главная перерисуется уже цифрами нового автосервиса.
 */
export function resolvePointSwitchReturn(below: RouteBelowPoints | null | undefined): 'back' | 'dashboard' {
  return isComposingNewCheckBelow(below) ? 'back' : 'dashboard';
}
