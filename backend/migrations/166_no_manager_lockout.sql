-- ============================================================================
-- ВЛАДЕЛЕЦ БОЛЬШЕ НЕ МОЖЕТ ЗАПЕРЕТЬ САМ СЕБЯ (последствие 165).
--
-- ── ЧТО СЛОМАЛОСЬ ───────────────────────────────────────────────────────────
-- 165 закрыла эскалацию: ветка «доступны все живые филиалы» включается только
-- при ПОЛНОМ отсутствии строк user_points, а не при отсутствии назначений на
-- живые филиалы. Иначе архивация филиала РАЗДАВАЛА доступ ко всей сети —
-- мастер, приписанный только к «ТопГазу», после его закрытия попадал в
-- основной сервис, где лежат деньги всей компании.
--
-- Но у правила оказалась вторая сторона. Владелец (роль director) работает в
-- филиале и назначает себя ТОЛЬКО на него. Суперадмин архивирует филиал —
-- и владелец получает пустой список доступных филиалов: вход отвечает
-- «Вам не назначен ни один действующий филиал», живая сессия получает 401,
-- и войти, чтобы исправить СОБСТВЕННЫЕ назначения, он больше не может НИКУДА.
-- Тупик, из которого пользователь не выбирается своими силами: единственный,
-- кто вправе раздавать доступы, лишён доступа.
--
-- ── ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ВЕРНУТЬ СТАРУЮ ВЕТКУ ───────────────────────────────
-- «Нет живых назначений → доступны все живые» — это ровно та эскалация,
-- которую закрыла 165. Обычный сотрудник в основной сервис попасть не должен
-- ни при каких обстоятельствах: там деньги всей сети.
--
-- ── РЕШЕНИЕ: РАЗВОДИМ ПО ВОЗМОЖНОСТЯМ, А НЕ ПУСКАЕМ ВСЕХ ────────────────────
-- Различие проходит по праву УПРАВЛЕНИЯ ПЕРСОНАЛОМ (user_management ←
-- матрица роли employees.manage; владелец/директор и суперадмин держат его по
-- роли). Держатель этого права И ТАК управляет филиалами и назначениями — для
-- него доступ к основному сервису не повышение прав, а то, чем он уже
-- распоряжается. Поэтому:
--
--   • НЕТ НИ ОДНОЙ строки user_points  → доступны все живые филиалы
--     (безопасный дефолт внедрения 156/163, дословно как было);
--   • назначения ЕСТЬ, живых среди них НЕТ, право управления персоналом ЕСТЬ
--     → доступен ОДИН филиал — основной сервис. Ровно столько, сколько нужно,
--     чтобы войти и починить назначения; сеть целиком не раздаётся;
--   • назначения ЕСТЬ, живых среди них НЕТ, права управления персоналом НЕТ
--     → пусто. Вход честно отказывает «обратитесь к руководителю» — это и
--     была та самая эскалация, её оставляем закрытой.
--
-- ── ПОЧЕМУ ПРАВИЛО ЖИВЁТ ЗДЕСЬ, А НЕ В КОДЕ ─────────────────────────────────
-- «Кому какие филиалы доступны» спрашивают ЧЕТЫРЕ пути, и все четыре уже
-- ходят в autexa_available_points (напрямую или через производные функции):
--   1. вход                        — AuthService.login → availablePoints();
--   2. обмен на сессию (шаг 2)     — AuthService.selectPoint → availablePoints();
--   3. проверка на каждом запросе  — JwtStrategy → autexa_point_is_allowed();
--   4. подстановка по умолчанию    — JwtStrategy / login старых сборок,
--                                    impersonate из ЛК → autexa_default_point();
--   (+ подсказка следующего входа  — PointsService.switchPoint → allowed()).
-- Правка ОДНОЙ функции чинит все пять. Любая копия правила в TypeScript
-- означала бы, что один из путей рано или поздно отстанет — а отстающий путь
-- в вопросе доступа это либо запертый владелец, либо открытая чужая касса.
--
-- ── ИДЕМПОТЕНТНО ───────────────────────────────────────────────────────────
-- Только CREATE OR REPLACE FUNCTION, схема не трогается. Повторный прогон
-- сходится к тому же состоянию.
-- ============================================================================

-- ── 1. ДЕРЖИТ ЛИ СОТРУДНИК ПРАВО УПРАВЛЕНИЯ ПЕРСОНАЛОМ ──────────────────────
-- ЗЕРКАЛО userHasPermission(actor, 'user_management') из
-- backend/src/common/guards/permissions.guard.ts. Порядок ветвей ДОСЛОВНО
-- тот же, иначе «кто вправе войти» в базе и «кто вправе управлять людьми» в
-- приложении разойдутся:
--   1. owner-class роль (director / superadmin) — всегда true;
--   2. матрица назначенной роли авторитетна: employees.manage true/false
--      (у роли с матрицей ячейка всегда определена — flattenRoleMatrix
--      материализует её как false, если её нет в JSON);
--   3. матрицы нет вовсе (role_id NULL либо роль удалена — аномалия после
--      cutover-миграции 126) → дефолт роли: admin = true
--      (ADMIN_PERMISSION_DEFAULTS.user_management), остальные false.
--
-- Сравнение через ->> 'true', а не ::boolean: мусор в ячейке уронил бы приведение
-- типа и вместе с ним КАЖДЫЙ auth-запрос — fail-closed важнее точности.
--
-- Пользователя нет → false (COALESCE поверх пустой выборки): несуществующему
-- актору не выдаём ничего.
CREATE OR REPLACE FUNCTION autexa_can_manage_staff(p_user uuid)
RETURNS boolean
LANGUAGE sql STABLE AS $autexa$
  SELECT COALESCE((
    SELECT CASE
             WHEN u.role IN ('director', 'superadmin')            THEN true
             WHEN r.matrix IS NOT NULL                            THEN (r.matrix -> 'employees' ->> 'manage') = 'true'
             WHEN u.role = 'admin'                                THEN true
             ELSE false
           END
      FROM users u
      LEFT JOIN roles r ON r.id = u.role_id
     WHERE u.id = p_user
  ), false)
$autexa$;

-- ── 2. ДОСТУПНЫЕ ФИЛИАЛЫ СОТРУДНИКА (замена версии из 165) ───────────────────
-- Сигнатура и контракт прежние: живые филиалы, в которых сотрудник вправе
-- работать, без фиксированного порядка (сортирует вызывающий — планировщик
-- волен инлайнить функцию и потерять внутренний ORDER BY).
--
-- p_tenant IS NULL (глобальный суперадмин без тенанта) → пусто, как и раньше.
CREATE OR REPLACE FUNCTION autexa_available_points(
    p_tenant uuid,
    p_user   uuid
) RETURNS TABLE(id uuid, name text, address text, is_main boolean, sort_order int)
LANGUAGE sql STABLE AS $autexa$
  WITH live AS (
    SELECT p.id, p.name, p.address, p.is_main, p.sort_order
      FROM tenant_points p
     WHERE p.tenant_id = p_tenant
       AND p.is_active
  ),
  assigned AS (
    -- Есть ли у сотрудника ХОТЬ ОДНО назначение — живое или на закрытый
    -- филиал. Именно этим признаком 165 развела «доступ не настроен» и
    -- «доступ настроен, но филиал закрыт»; обе ветки ниже опираются на него.
    SELECT EXISTS (
      SELECT 1 FROM user_points up
       WHERE up.user_id = p_user
         AND up.tenant_id = p_tenant
    ) AS any_row
  ),
  mine AS (
    SELECT l.* FROM live l
     WHERE EXISTS (
       SELECT 1 FROM user_points up
        WHERE up.point_id = l.id
          AND up.user_id  = p_user
          AND up.tenant_id = p_tenant
     )
  )
  SELECT * FROM mine
  UNION ALL
  -- «ДОСТУП НЕ НАСТРОЕН» — и только он (165). Безопасный дефолт внедрения:
  -- тенант, который никого никуда не назначал, работает без единой настройки.
  SELECT * FROM live
   WHERE NOT (SELECT any_row FROM assigned)
  UNION ALL
  -- «ДОСТУП НАСТРОЕН, НО ВСЕ ФИЛИАЛЫ ЗАКРЫТЫ» + право управления персоналом
  -- (166). Отдаём РОВНО ОДИН филиал — основной сервис, — чтобы владелец мог
  -- войти и починить собственные назначения. Не всю сеть: минимум, которого
  -- достаточно для выхода из тупика.
  --
  -- LIMIT 1 с явным ORDER BY, а не `WHERE l.is_main`: порядок тот же, что у
  -- autexa_default_point и у всех пикеров (основной сервис → sort_order → имя
  -- → id), поэтому база без основной точки (её гарантируют 160/162, а
  -- PointsService запрещает её архивировать — но гарантия не должна быть
  -- единственной опорой правила «запереться нельзя») отдаёт первый живой
  -- филиал вместо пустоты. id в хвосте — чтобы две одноимённые точки с равным
  -- sort_order давали ОДИН И ТОТ ЖЕ ответ на любой реплике.
  SELECT * FROM (
    SELECT l.* FROM live l
     ORDER BY l.is_main DESC, l.sort_order ASC, lower(l.name) ASC, l.id ASC
     LIMIT 1
  ) main_fallback
   WHERE (SELECT any_row FROM assigned)
     AND NOT EXISTS (SELECT 1 FROM mine)
     AND autexa_can_manage_staff(p_user)
$autexa$;
