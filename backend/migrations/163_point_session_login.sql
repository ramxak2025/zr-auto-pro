-- ФИЛИАЛ — СВОЙСТВО СЕССИИ, А НЕ СТРОКИ ПОЛЬЗОВАТЕЛЯ.
--
-- ЧТО БЫЛО НЕ ТАК. Филиал жил в users.current_point_id и менялся ручкой
-- POST /points/switch. Отсюда два класса ошибок, каждый — про деньги:
--   • ОДНА КОЛОНКА НА ВСЕ УСТРОЙСТВА. Владелец переключал филиал на телефоне —
--     и его же веб-сессия молча уезжала в тот же филиал. Человек смотрел на
--     экран, подписанный одним автосервисом, а сервер отдавал деньги другого.
--   • РЕЖИМ «ВСЕ ФИЛИАЛЫ» КАК РАБОЧИЙ. current_point_id = NULL означал
--     «фильтра нет». Запись в этом режиме рождала строку без филиала, а
--     филиальные срезы фильтруют СТРОГИМ равенством — такая выплата не
--     вычиталась из «к выплате» НИ В ОДНОМ филиале, и зарплату выдавали второй
--     раз.
--
-- РЕШЕНИЕ (владелец, дословно): «филиал переключался только в разделе Филиалы,
-- и чтобы в пользователях была настройка, на каких филиалах они могут
-- работать… им показывал выбор, в какой филиал из доступных для них они могли
-- зайти… чтобы выйти и войти в другой им надо опять выйти и войти».
-- Технически: филиал уезжает В ТОКЕН при входе и живёт ровно столько, сколько
-- живёт сессия. Смена филиала = выход и вход заново. Режима «все филиалы» у
-- сессии больше нет: сводка по сети осталась карточками GET /points/summary.
--
-- ЭТА МИГРАЦИЯ НЕ МЕНЯЕТ СХЕМУ — она заводит ТРИ ФУНКЦИИ-ПРЕДИКАТА, чтобы
-- вопрос «какие филиалы доступны этому сотруднику» имел РОВНО ОДИН ответ на
-- весь монорепо. До неё этот ответ был скопирован трижды (PointsService
-- .listForTenant, PointsService.defaultPointForMember, point-scope
-- .resolvePointForWrite), и копии уже начали расходиться порядком сортировки:
-- одна ставила «первым» филиал по created_at, другая по имени. «Первый»
-- филиал — это тот, в который человек попадёт по умолчанию, то есть филиал,
-- на счёт которого пойдут его деньги. Расхождение здесь — не косметика.
--
-- КОНВЕНЦИЯ ДОСТУПА (заведена 156 и сохраняется дословно): у сотрудника есть
-- назначения на ЖИВЫЕ филиалы (user_points) → доступны только они; назначений
-- на живые филиалы нет ВООБЩЕ → доступны все живые филиалы тенанта. Вторая
-- ветка — безопасный дефолт внедрения: тенант, который никого никуда не
-- назначал, продолжает работать без единой настройки. Она же закрывает случай
-- «сотрудник назначен только на заархивированный филиал»: иначе он не смог бы
-- войти вообще никуда.
--
-- ИДЕМПОТЕНТНО: только CREATE OR REPLACE FUNCTION. Повторный прогон сходится к
-- тому же состоянию. Файл не редактируется после применения.
-- ============================================================================

-- ── 1. ДОСТУПНЫЕ ФИЛИАЛЫ СОТРУДНИКА ─────────────────────────────────────────
-- Возвращает ЖИВЫЕ филиалы, в которых сотрудник имеет право работать. Порядок
-- НЕ фиксируется внутри (планировщик волен инлайнить функцию и потерять его) —
-- сортирует вызывающий, для чего функция и отдаёт is_main / sort_order / name.
--
-- p_tenant IS NULL (глобальный суперадмин без тенанта) → пусто: филиалов у него
-- нет, и сессия честно остаётся без филиала.
CREATE OR REPLACE FUNCTION autexa_available_points(
    p_tenant uuid,
    p_user   uuid
) RETURNS TABLE(id uuid, name text, address text, is_main boolean, sort_order int)
LANGUAGE sql STABLE AS $autexa$
  WITH live AS (
    SELECT p.id, p.name, p.address, p.is_main, p.sort_order
      FROM tenant_points p
     WHERE p.tenant_id = p_tenant
       AND p.is_active
  ),
  mine AS (
    SELECT l.* FROM live l
     WHERE EXISTS (
       SELECT 1 FROM user_points up
        WHERE up.point_id = l.id
          AND up.user_id  = p_user
          AND up.tenant_id = p_tenant
     )
  )
  SELECT * FROM mine
  UNION ALL
  SELECT * FROM live WHERE NOT EXISTS (SELECT 1 FROM mine)
$autexa$;

-- ── 2. МОЖНО ЛИ ЭТОЙ СЕССИИ РАБОТАТЬ В ЭТОМ ФИЛИАЛЕ ─────────────────────────
-- Проверка выполняется на КАЖДОМ запросе (JwtStrategy, через 30-секундный
-- auth-кеш), поэтому снятие доступа и архивация филиала обязаны обесточивать
-- живую сессию: токен подписан, но филиал в нём больше не разрешён — 401 и
-- вход заново. Без этой проверки уволенный из филиала сотрудник продолжал бы
-- пробивать в нём чеки до истечения 30-дневного токена.
CREATE OR REPLACE FUNCTION autexa_point_is_allowed(
    p_tenant uuid,
    p_user   uuid,
    p_point  uuid
) RETURNS boolean
LANGUAGE sql STABLE AS $autexa$
  SELECT EXISTS (
    SELECT 1 FROM autexa_available_points(p_tenant, p_user) a WHERE a.id = p_point
  )
$autexa$;

-- ── 3. ФИЛИАЛ ПО УМОЛЧАНИЮ ──────────────────────────────────────────────────
-- Кому нужен: клиенту СТАРОЙ сборки (3.5/3.6), который про выбор филиала не
-- знает и ждёт токен сразу, и сессии, чей токен выписан до этой волны.
--
-- p_preferred — «последний выбранный» (users.current_point_id). Он честно
-- выигрывает, НО только если сотруднику всё ещё доступен: иначе снятие доступа
-- возвращало бы человека ровно туда, откуда его убрали. Дальше — тот же
-- порядок, что во всех пикерах: основной сервис, затем sort_order, имя, id.
-- id в хвосте — не украшение: без него два одноимённых филиала с равным
-- sort_order давали бы РАЗНЫЙ ответ на разных репликах, то есть деньги
-- сотрудника уходили бы то в один филиал, то в другой.
--
-- NULL = у тенанта нет ни одного живого филиала (одноточечный автосервис).
-- Это единственный случай, когда сессия остаётся без филиала, и именно он
-- сохраняет одноточечному тенанту прежнее поведение байт-в-байт.
CREATE OR REPLACE FUNCTION autexa_default_point(
    p_tenant    uuid,
    p_user      uuid,
    p_preferred uuid
) RETURNS uuid
LANGUAGE sql STABLE AS $autexa$
  SELECT a.id
    FROM autexa_available_points(p_tenant, p_user) a
   ORDER BY COALESCE(a.id = p_preferred, false) DESC,
            a.is_main DESC,
            a.sort_order ASC,
            lower(a.name) ASC,
            a.id ASC
   LIMIT 1
$autexa$;
