-- 160_points_scoping.sql
-- ============================================================================
-- Филиалы: ОСНОВНОЙ СЕРВИС + скоуп чтения. Продолжение 156 (tenant_points /
-- user_points / checks.point_id / clients.point_id / tenants.points_shared_clients).
--
-- ЗАЧЕМ. 156 завела колонки, но реально скоуп работал только в списке
-- клиентов. Начиная с этой волны точка режет журнал, доску, дашборды,
-- «Движение денег» и отчёты. Отсюда три задачи миграции:
--
--   0. ПОНЯТИЕ ОСНОВНОГО СЕРВИСА. В 156 его не было: tenant_points — плоский
--      список, который заводит суперадмин. Между тем автосервис владельца —
--      это САМ ТЕНАНТ (его имя лежит в tenants.name), а всё, что суперадмин
--      добавляет сверху, — дополнительно открытые филиалы. Формулировка
--      владельца дословно: «Должен быть основной сервис, он называется
--      ZR AUTO, а филиал ТопГаз — это дополнительно открытый. Это два разных
--      автосервиса одного владельца просто».
--
--      Поэтому здесь появляется tenant_points.is_main и жёсткая гарантия
--      «ровно одна основная точка на тенанта». Как только у тенанта есть хотя
--      бы одна ЖИВАЯ точка, основная обязана существовать — либо ею
--      помечается уже заведённая точка с именем компании, либо она заводится
--      из tenants.name.
--
--   1. РАЗОВАЯ ПРИВЯЗКА ИСТОРИИ — К ОСНОВНОЙ ТОЧКЕ. Все чеки и клиенты,
--      созданные ДО внедрения точек, имеют point_id IS NULL. Фильтр филиала —
--      СТРОГОЕ равенство (см. backend/src/common/point-scope.ts: «ИЛИ NULL»
--      показывал бы одну и ту же строку в каждом филиале и задваивал деньги
--      при сравнении точек), поэтому без привязки вся история пропала бы из
--      филиального среза.
--
--      КОМУ ЭТА ИСТОРИЯ ПРИНАДЛЕЖИТ. Только основному сервису. Владелец годами
--      работал как ZR AUTO, потом открыл ТопГаз — и суперадмин завёл в системе
--      ОДНУ точку, «ТопГаз». Привязка «к первой живой точке по sort_order»
--      (как было в первой редакции этого файла) пометила бы всю многолетнюю
--      историю ZR AUTO как ТопГаз. Обратно различить нечем: до миграции у всех
--      строк точка пустая, признака «чьё это» не существует — деньги, клиенты
--      и зарплата двух РАЗНЫХ автосервисов схлопнулись бы в один необратимо.
--      Отсюда правило: историческая строка без точки принадлежит ОСНОВНОМУ
--      сервису и никогда — филиалу.
--
--      КОГО ТРОГАЕМ: только тенантов, у которых точки УЖЕ ЗАВЕДЕНЫ (есть хотя
--      бы одна живая tenant_points). Тенант без точек — обычный одноточечный
--      автосервис: привязывать не к чему, его строки остаются NULL, и
--      фильтра у него всё равно никогда не будет. По той же причине основная
--      точка НЕ заводится тенанту, у которого живых точек нет вовсе: это
--      молча включило бы ему мульти-точечный режим, которого он не просил.
--
--      ПОЧЕМУ И ТЕНАНТА С ОДНОЙ ТОЧКОЙ ТОЖЕ: сегодня это ничего не меняет
--      (одна точка = «его» точка), но в день, когда суперадмин заведёт ему
--      вторую, ВСЯ прежняя история одномоментно стала бы «ничьей» и исчезла
--      из обоих филиалов. Привязка сейчас — это ровно то, что мешает потерять
--      деньги потом. Обратное («трогаем только тех, у кого ≥2 точек») выглядит
--      аккуратнее, но оставляет мину.
--
--   2. ИНДЕКСЫ ПОД НОВЫЕ ФИЛЬТРЫ. Журнал ходит курсором по keyset-индексу из
--      139 (tenant_id, date DESC, created_at DESC, id DESC). С добавленным
--      `point_id = $n` этот индекс перестаёт быть покрывающим: Postgres
--      сканирует ленту ВСЕГО тенанта и отбрасывает чужие филиалы строка за
--      строкой — у сети из пяти точек это пятикратный лишний ввод-вывод на
--      каждую страницу журнала, каждые 30 секунд опроса. Нужен зеркальный
--      индекс с точкой во главе.
--
-- ИДЕМПОТЕНТНОСТЬ. ADD COLUMN / CREATE INDEX IF NOT EXISTS; пометка и создание
-- основной точки выполняются только при её отсутствии (NOT EXISTS), поэтому
-- второй прогон не плодит дублей; UPDATE'ы истории адресуют только строки с
-- point_id IS NULL, поэтому повторный прогон не переписывает уже привязанные
-- строки (и не «переносит» деньги между филиалами).
--
-- РЕМОНТ УЖЕ ИСПОРЧЕННОЙ БАЗЫ — в 162_points_main_repair.sql: этот файл мог
-- быть применён в старой редакции (привязка к первой живой точке) на локальной
-- или тестовой базе, а повторно MigrationRunner его не выполнит.
-- ============================================================================

-- ── 0. Признак основного сервиса ────────────────────────────────────────────

-- is_main = «эта точка и есть сам автосервис тенанта», остальные — филиалы.
-- Дефолт false: существующие строки становятся филиалами, а основную мы ниже
-- либо находим по имени компании, либо заводим.
ALTER TABLE tenant_points ADD COLUMN IF NOT EXISTS is_main BOOLEAN NOT NULL DEFAULT false;

-- РОВНО ОДНА основная на тенанта — гарантия уровня БД, а не соглашение в коде.
-- Частичный индекс (WHERE is_main) не мешает произвольному числу филиалов и
-- физически исключает состояние «две основные»: именно оно сделало бы вопрос
-- «чья это история» снова неразрешимым. Архивные точки индексом тоже
-- покрываются — основная не может быть заархивирована (см. PointsService).
CREATE UNIQUE INDEX IF NOT EXISTS uq_tenant_points_one_main
    ON tenant_points (tenant_id) WHERE is_main;

-- Шаг 0.1: у тенанта есть живые точки, основной среди них нет, и одна из живых
-- точек НАЗЫВАЕТСЯ КАК КОМПАНИЯ → она и есть основной сервис. Помечаем ЕЁ, а не
-- плодим дубль: иначе в списке появились бы две «ZR AUTO», и владелец не понял
-- бы, в какую из них смотреть.
--
-- Сравнение имени — case-insensitive и без краевых пробелов, ровно как в
-- частичном уникальном индексе имён из 156 (lower(name) среди живых).
-- Пустое имя компании подменяем на 'Основной' — тем же выражением, что и в
-- шаге 0.2, чтобы вставка ниже не столкнулась с уже существующей точкой
-- 'Основной' и не упала на уникальном индексе имён (23505 = падение старта).
-- DISTINCT ON — страховка от гонки: уникальный индекс имён среди живых точек и
-- так допускает максимум одно совпадение.
UPDATE tenant_points tp
   SET is_main = true
  FROM (
        SELECT DISTINCT ON (p.tenant_id) p.tenant_id, p.id
          FROM tenant_points p
          JOIN tenants t ON t.id = p.tenant_id
         WHERE p.is_active
           AND lower(btrim(p.name)) = lower(COALESCE(NULLIF(btrim(t.name), ''), 'Основной'))
           AND NOT EXISTS (SELECT 1 FROM tenant_points m WHERE m.tenant_id = p.tenant_id AND m.is_main)
         ORDER BY p.tenant_id, p.sort_order ASC, p.created_at ASC, p.id ASC
       ) pick
 WHERE tp.id = pick.id;

-- Шаг 0.2: живые точки есть, основной по-прежнему нет → заводим её из
-- tenants.name. Это и есть «ZR AUTO» из формулировки владельца: сервис, с
-- которого всё начиналось и которому принадлежит вся история.
--
-- sort_order = MIN(существующих) − 1: основная обязана идти первой даже там,
-- где сортируют голым sort_order. Тенант без точек сюда не попадает (EXISTS
-- по живым точкам), так что MIN всегда есть; COALESCE — защита от гонки.
INSERT INTO tenant_points (tenant_id, name, address, sort_order, is_active, is_main)
SELECT t.id,
       COALESCE(NULLIF(btrim(t.name), ''), 'Основной'),
       NULL,
       COALESCE((SELECT MIN(p2.sort_order) FROM tenant_points p2 WHERE p2.tenant_id = t.id), 1) - 1,
       true,
       true
  FROM tenants t
 WHERE EXISTS (SELECT 1 FROM tenant_points p WHERE p.tenant_id = t.id AND p.is_active)
   AND NOT EXISTS (SELECT 1 FROM tenant_points m WHERE m.tenant_id = t.id AND m.is_main);

-- ── 1. История без точки → ОСНОВНАЯ точка тенанта ───────────────────────────
-- Подзапрос отдаёт ровно одну строку на тенанта: уникальный индекс
-- uq_tenant_points_one_main это гарантирует физически, поэтому DISTINCT ON и
-- разрыватели ничьих здесь не нужны — «первой попавшейся» точки больше не
-- существует как понятия.

-- Чеки без точки → основной сервис своего тенанта.
UPDATE checks ch
   SET point_id = mp.point_id
  FROM (
        SELECT tp.tenant_id, tp.id AS point_id
          FROM tenant_points tp
         WHERE tp.is_main AND tp.is_active
       ) mp
 WHERE ch.point_id IS NULL
   AND ch.tenant_id = mp.tenant_id;

-- Клиенты без точки → тот же основной сервис. Нужно ровно для того же:
-- в раздельном режиме (tenants.points_shared_clients=false) исторический
-- клиент с NULL сейчас виден всем точкам, и при появлении второй точки его
-- принадлежность стала бы неопределённой.
UPDATE clients cl
   SET point_id = mp.point_id
  FROM (
        SELECT tp.tenant_id, tp.id AS point_id
          FROM tenant_points tp
         WHERE tp.is_main AND tp.is_active
       ) mp
 WHERE cl.point_id IS NULL
   AND cl.tenant_id = mp.tenant_id;

-- ── 2. Индексы под фильтр филиала ───────────────────────────────────────────

-- Курсорный журнал филиала: точная копия keyset-индекса 139 с point_id сразу
-- после tenant_id. Порядок колонок совпадает с ORDER BY (все DESC), поэтому
-- Postgres идёт по индексу вперёд, без сортировки, и сразу в нужном филиале.
-- Частичный (deleted_at IS NULL) — корзина в журнал не входит, как и в 139.
-- Индекс 139 остаётся: по нему ходит владелец в режиме «Все точки».
CREATE INDEX IF NOT EXISTS idx_checks_tenant_point_date_created_id
  ON checks (tenant_id, point_id, date DESC, created_at DESC, id DESC)
  WHERE deleted_at IS NULL;

-- Денежные агрегаты филиала (дашборд, dashboard-v2, «Движение денег»,
-- финотчёт, сводка по филиалам): все они читают проведённые живые чеки за
-- диапазон дат одной точки. Частичный по is_deferred=false AND
-- deleted_at IS NULL — драфты и корзина в деньги не входят, а без них индекс
-- заметно меньше и горячее.
CREATE INDEX IF NOT EXISTS idx_checks_tenant_point_money_date
  ON checks (tenant_id, point_id, date)
  WHERE is_deferred = false AND deleted_at IS NULL;

-- Доска-конвейер филиала: чеки точки в активных колонках. Зеркало
-- idx_checks_tenant_workstatus (082) с точкой.
CREATE INDEX IF NOT EXISTS idx_checks_tenant_point_workstatus
  ON checks (tenant_id, point_id, work_status)
  WHERE work_status IS NOT NULL AND deleted_at IS NULL;
