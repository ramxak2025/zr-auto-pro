-- Филиалы: скоуп чтения. Продолжение 156 (tenant_points / user_points /
-- checks.point_id / clients.point_id / tenants.points_shared_clients).
--
-- ЗАЧЕМ. 156 завела колонки, но реально скоуп работал только в списке
-- клиентов. Начиная с этой волны точка режет журнал, доску, дашборды,
-- «Движение денег» и отчёты. Отсюда две задачи миграции:
--
--   1. РАЗОВАЯ ПРИВЯЗКА ИСТОРИИ. Все чеки и клиенты, созданные ДО внедрения
--      точек, имеют point_id IS NULL. Фильтр филиала — СТРОГОЕ равенство
--      (см. backend/src/common/point-scope.ts: «ИЛИ NULL» показывал бы одну и
--      ту же строку в каждом филиале и задваивал деньги при сравнении точек),
--      поэтому без привязки вся история пропала бы из филиального среза.
--      Прибиваем к ПЕРВОЙ ЖИВОЙ точке тенанта — той, что стоит первой в
--      пикере (sort_order, затем created_at, затем id — детерминированно).
--
--      КОГО ТРОГАЕМ: только тенантов, у которых точки УЖЕ ЗАВЕДЕНЫ (есть хотя
--      бы одна живая tenant_points). Тенант без точек — обычный одноточечный
--      автосервис: привязывать не к чему, его строки остаются NULL, и
--      фильтра у него всё равно никогда не будет.
--
--      ПОЧЕМУ И ТЕНАНТА С ОДНОЙ ТОЧКОЙ ТОЖЕ: сегодня это ничего не меняет
--      (одна точка = «его» точка), но в день, когда суперадмин заведёт ему
--      вторую, ВСЯ прежняя история одномоментно стала бы «ничьей» и исчезла
--      из обоих филиалов. Привязка сейчас — это ровно то, что мешает потерять
--      деньги потом. Обратное («трогаем только тех, у кого ≥2 точек») выглядит
--      аккуратнее, но оставляет мину.
--
--   2. ИНДЕКСЫ ПОД НОВЫЕ ФИЛЬТРЫ. Журнал ходит курсором по keyset-индексу из
--      139 (tenant_id, date DESC, created_at DESC, id DESC). С добавленным
--      `point_id = $n` этот индекс перестаёт быть покрывающим: Postgres
--      сканирует ленту ВСЕГО тенанта и отбрасывает чужие филиалы строка за
--      строкой — у сети из пяти точек это пятикратный лишний ввод-вывод на
--      каждую страницу журнала, каждые 30 секунд опроса. Нужен зеркальный
--      индекс с точкой во главе.
--
-- ИДЕМПОТЕНТНОСТЬ. UPDATE'ы адресуют только строки с point_id IS NULL, поэтому
-- повторный прогон не переписывает уже привязанные строки (и не «переносит»
-- деньги между филиалами). CREATE INDEX IF NOT EXISTS. Файл после применения
-- не редактируется.
-- ============================================================================

-- ── 1. Первая живая точка каждого тенанта ───────────────────────────────────
-- DISTINCT ON даёт ровно одну строку на тенанта. Порядок — как в пикере
-- (PointsService.listForTenant): sort_order, затем время создания, затем id
-- как финальный разрыватель ничьих, чтобы результат не зависел от плана
-- выполнения.

-- Чеки без точки → первая живая точка своего тенанта.
UPDATE checks ch
   SET point_id = fp.point_id
  FROM (
        SELECT DISTINCT ON (tp.tenant_id) tp.tenant_id, tp.id AS point_id
          FROM tenant_points tp
         WHERE tp.is_active
         ORDER BY tp.tenant_id, tp.sort_order ASC, tp.created_at ASC, tp.id ASC
       ) fp
 WHERE ch.point_id IS NULL
   AND ch.tenant_id = fp.tenant_id;

-- Клиенты без точки → та же первая живая точка. Нужно ровно для того же:
-- в раздельном режиме (tenants.points_shared_clients=false) исторический
-- клиент с NULL сейчас виден всем точкам, и при появлении второй точки его
-- принадлежность стала бы неопределённой.
UPDATE clients cl
   SET point_id = fp.point_id
  FROM (
        SELECT DISTINCT ON (tp.tenant_id) tp.tenant_id, tp.id AS point_id
          FROM tenant_points tp
         WHERE tp.is_active
         ORDER BY tp.tenant_id, tp.sort_order ASC, tp.created_at ASC, tp.id ASC
       ) fp
 WHERE cl.point_id IS NULL
   AND cl.tenant_id = fp.tenant_id;

-- ── 2. Индексы под фильтр филиала ───────────────────────────────────────────

-- Курсорный журнал филиала: точная копия keyset-индекса 139 с point_id сразу
-- после tenant_id. Порядок колонок совпадает с ORDER BY (все DESC), поэтому
-- Postgres идёт по индексу вперёд, без сортировки, и сразу в нужном филиале.
-- Частичный (deleted_at IS NULL) — корзина в журнал не входит, как и в 139.
-- Индекс 139 остаётся: по нему ходит владелец в режиме «Все точки».
CREATE INDEX IF NOT EXISTS idx_checks_tenant_point_date_created_id
  ON checks (tenant_id, point_id, date DESC, created_at DESC, id DESC)
  WHERE deleted_at IS NULL;

-- Денежные агрегаты филиала (дашборд, dashboard-v2, «Движение денег»,
-- финотчёт, сводка по филиалам): все они читают проведённые живые чеки за
-- диапазон дат одной точки. Частичный по is_deferred=false AND
-- deleted_at IS NULL — драфты и корзина в деньги не входят, а без них индекс
-- заметно меньше и горячее.
CREATE INDEX IF NOT EXISTS idx_checks_tenant_point_money_date
  ON checks (tenant_id, point_id, date)
  WHERE is_deferred = false AND deleted_at IS NULL;

-- Доска-конвейер филиала: чеки точки в активных колонках. Зеркало
-- idx_checks_tenant_workstatus (082) с точкой.
CREATE INDEX IF NOT EXISTS idx_checks_tenant_point_workstatus
  ON checks (tenant_id, point_id, work_status)
  WHERE work_status IS NOT NULL AND deleted_at IS NULL;
