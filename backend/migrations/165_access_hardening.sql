-- ── 1. АРХИВАЦИЯ ФИЛИАЛА РАЗДАВАЛА ДОСТУП КО ВСЕЙ СЕТИ ──────────────────────
--
-- Конвенция 156/163 звучала так: «есть назначения на ЖИВЫЕ филиалы → доступны
-- только они; назначений на живые филиалы нет → доступны ВСЕ живые филиалы».
-- Вторая ветка задумывалась как безопасный дефолт внедрения — тенант, который
-- никого никуда не назначал, работает без единой настройки.
--
-- Но у неё оказался второй, незапланированный вход. Формулировка «нет
-- назначений НА ЖИВЫЕ филиалы» смешивала два РАЗНЫХ состояния:
--     • «доступ не настроен»      — у сотрудника нет назначений вообще;
--     • «доступ настроен, но филиал закрыт» — назначения есть, но все они
--       указывают на заархивированные филиалы.
-- Второе состояние проваливалось в ветку «доступны все живые». Отсюда
-- сценарий, ради которого этот файл и написан: мастер назначен ТОЛЬКО на
-- филиал «ТопГаз», суперадмин архивирует «ТопГаз» — и мастер в ту же секунду
-- получает доступ к ОСНОВНОМУ сервису, где лежат деньги всей компании и куда
-- его никогда не пускали. Закрытие филиала обязано ОТНИМАТЬ доступ, а не
-- выдавать новый.
--
-- ЧТО МЕНЯЕТСЯ: ветка «доступны все живые» теперь включается по признаку «у
-- сотрудника НЕТ НИ ОДНОЙ строки user_points» (живой ли филиал в ней — не
-- важно), а не по признаку «нет назначений на живые». Безопасный дефолт для
-- несконфигурированных команд сохранён дословно: у них строк нет, ветка
-- работает как раньше. Сотрудник, назначенный только на закрытый филиал,
-- получает ПУСТОЙ список — то есть «доступа нет», и вход честно отказывает
-- (AuthService.login) вместо того, чтобы молча пустить его в чужие деньги.
--
-- ПОЧЕМУ ЭТО БЕЗОПАСНО ДЛЯ ЖИВЫХ ТЕНАНТОВ: строку user_points заводит только
-- явное действие владельца (PUT /points/:id/members или PUT /users/:id/points).
-- Пока владелец никого не назначал, поведение прежнее байт-в-байт.
--
-- ── 2. СМЕНА ПАРОЛЯ НЕ ГАСИЛА СТАРЫЕ СЕССИИ ─────────────────────────────────
--
-- Пароль менялся, а ранее выданные токены жили до 30 суток: украденный или
-- оставшийся на чужом телефоне токен продолжал работать, и сменить пароль
-- «чтобы выгнать чужого» было НЕВОЗМОЖНО. Механизм ревокации (021) адресует
-- ОДИН токен по jti — списка живых jti пользователя нигде нет, поэтому «выгнать
-- все сессии» им не выразить.
--
-- users.sessions_valid_from — граница: токен, выписанный РАНЬШЕ этого момента,
-- недействителен, сколько бы ни оставалось до его exp. Сравнение идёт с claim
-- `iat` в JwtStrategy тем же запросом, что роль и филиал (ноль лишних обращений
-- к БД), и выполняется В БАЗЕ — часы Node и Postgres расходиться не обязаны.
--
-- NULL (дефолт) = границы нет, все выданные сессии действительны. Именно
-- поэтому у колонки НЕТ DEFAULT now(): иначе применение миграции разлогинило бы
-- разом весь прод.
--
-- ИДЕМПОТЕНТНО: ADD COLUMN IF NOT EXISTS + CREATE OR REPLACE FUNCTION.
-- Повторный прогон сходится к тому же состоянию.
-- ============================================================================

-- ── 1. ДОСТУПНЫЕ ФИЛИАЛЫ СОТРУДНИКА (замена версии из 163) ───────────────────
-- Сигнатура и контракт прежние: живые филиалы, в которых сотрудник вправе
-- работать, без фиксированного порядка (сортирует вызывающий — планировщик
-- волен инлайнить функцию и потерять внутренний ORDER BY).
--
-- p_tenant IS NULL (глобальный суперадмин без тенанта) → пусто, как и раньше.
CREATE OR REPLACE FUNCTION autexa_available_points(
    p_tenant uuid,
    p_user   uuid
) RETURNS TABLE(id uuid, name text, address text, is_main boolean, sort_order int)
LANGUAGE sql STABLE AS $autexa$
  WITH live AS (
    SELECT p.id, p.name, p.address, p.is_main, p.sort_order
      FROM tenant_points p
     WHERE p.tenant_id = p_tenant
       AND p.is_active
  ),
  mine AS (
    SELECT l.* FROM live l
     WHERE EXISTS (
       SELECT 1 FROM user_points up
        WHERE up.point_id = l.id
          AND up.user_id  = p_user
          AND up.tenant_id = p_tenant
     )
  )
  SELECT * FROM mine
  UNION ALL
  -- «Доступ НЕ НАСТРОЕН» — и только он. Раньше здесь стояло
  -- `NOT EXISTS (SELECT 1 FROM mine)`, то есть «нет доступа к живым филиалам»,
  -- и архивация последнего назначенного филиала открывала сотруднику всю сеть.
  SELECT * FROM live
   WHERE NOT EXISTS (
     SELECT 1 FROM user_points up
      WHERE up.user_id = p_user
        AND up.tenant_id = p_tenant
   )
$autexa$;

-- ── 2. ГРАНИЦА ЖИЗНИ СЕССИЙ ПОЛЬЗОВАТЕЛЯ ────────────────────────────────────
-- Пишется при смене пароля (самим сотрудником — ProfileService.changePassword)
-- и при сбросе пароля владельцем (UsersService.update). Читается JwtStrategy.
ALTER TABLE users ADD COLUMN IF NOT EXISTS sessions_valid_from TIMESTAMPTZ;

COMMENT ON COLUMN users.sessions_valid_from IS
  'Токены с iat раньше этого момента недействительны (смена/сброс пароля). NULL = границы нет.';
