-- 158_salary_payout_viewed.sql
-- Выплата фиксируется СРАЗУ; подтверждение мастером заменено на «просмотрено».
--
-- WHY
--   Владелец: «убери подтверждение выплат мастером». До этого (100) выплата
--   жила в status='pending', и зеркальный расход писался ТОЛЬКО когда мастер
--   нажимал «Принять» (decidePayout). Мастера кнопку игнорировали — деньги из
--   кассы уже ушли, а в книгах расхода не было: «Выплачено» не росло, остаток
--   не уменьшался, владелец выдавал второй раз. Новая модель: выдал →
--   зафиксировано (status='accepted' + расход в ТОЙ ЖЕ транзакции), а у мастера
--   вместо «принять/отклонить» — уведомление, закрытие которого помечает
--   выплату ПРОСМОТРЕННОЙ. Владелец видит «просмотрено / не просмотрено».
--
-- WHAT
--   1) salary_payouts.viewed_at TIMESTAMPTZ — момент, когда ПОЛУЧАТЕЛЬ увидел
--      выплату (закрыл уведомление). NULL = «не просмотрено». Деньги от этой
--      колонки НЕ зависят: суммы «выплачено» по-прежнему считают status.
--   2) Бэкфилл ИСТОРИЧЕСКИХ принятых выплат: мастер, нажавший «Принять»,
--      выплату видел — viewed_at = decided_at.
--
-- ЧТО ДЕЛАЕМ СО СТАРЫМИ pending — НИЧЕГО (осознанно).
--   У pending-выплаты НЕТ зеркального расхода. Пометить её здесь 'accepted'
--   без расхода — потерять деньги в кассе; создать расход миграцией — выдумать
--   движение денег, которого владелец не подтверждал (мог выписать ошибочно и
--   ждать реакции). Обе ветки — тихая правка чужой бухгалтерии, поэтому старые
--   pending остаются как есть, а решение принимает ВЛАДЕЛЕЦ вручную:
--     • POST /salary/payouts/:id/settle  — зафиксировать (создаст расход);
--     • POST /salary/payouts/:id/cancel  — отменить.
--   В UI такие строки показаны отдельным блоком «Не зафиксированы» с этими
--   двумя действиями. Новые выплаты pending уже не создаются никогда.
--
-- IDEMPOTENT, append-only: guarded ADD COLUMN (DO-блок глотает
--   duplicate_column/undefined_table); бэкфилл ограничен строками, у которых
--   viewed_at ещё NULL И decided_at СТРОГО позже created_at — то есть решение
--   принималось ОТДЕЛЬНОЙ транзакцией (старый flow). У выплат нового flow
--   created_at = decided_at (одна транзакция), поэтому повторный прогон
--   миграции не пометит их «просмотренными» задним числом.

-- ── salary_payouts.viewed_at ────────────────────────────────────────────────
DO $$ BEGIN ALTER TABLE salary_payouts ADD COLUMN viewed_at TIMESTAMPTZ; EXCEPTION WHEN duplicate_column OR undefined_table THEN NULL; END $$;

-- Бэкфилл: принял выплату в старом flow → значит, видел её.
DO $$
BEGIN
  UPDATE salary_payouts
     SET viewed_at = decided_at
   WHERE status = 'accepted'
     AND viewed_at IS NULL
     AND decided_at IS NOT NULL
     AND decided_at > created_at;
EXCEPTION WHEN undefined_table OR undefined_column THEN NULL;
END $$;

-- Владельческий бейдж «не просмотрено» в списке выплат сотрудника: частичный
-- индекс по непросмотренным (их всегда единицы) — выборка по тенанту/сотруднику.
CREATE INDEX IF NOT EXISTS idx_salary_payouts_unviewed
  ON salary_payouts (tenant_id, employee_id)
  WHERE viewed_at IS NULL;
