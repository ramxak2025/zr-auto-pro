-- 129_rename_plan_garazh.sql
-- Переименование минимального тарифа «Личный» → «Гараж» (усиление enterprise-
-- позиционирования: «Гараж» = автосервис-организация, а не «личное» использование).
-- Название плана — display-поле (везде матчится по plan_id, не по имени), поэтому
-- переименование безопасно. Идемпотентно: повторный прогон не находит «Личный» → no-op.
-- Если владелец назвал минимальный тариф в кабинете иначе — этот UPDATE будет no-op,
-- и переименование делается вручную в кабинете суперадмина (Тарифы).
UPDATE plans SET name = 'Гараж' WHERE name = 'Личный';
