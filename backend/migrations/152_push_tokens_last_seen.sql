-- 152_push_tokens_last_seen.sql
-- ============================================================================
-- push_tokens.last_seen_at — когда устройство В ПОСЛЕДНИЙ РАЗ подтвердило, что
-- этот токен всё ещё его и всё ещё принадлежит этому пользователю.
--
-- Зачем (аудит мультитенантности уведомлений, гигиена):
--   • created_at отвечает на другой вопрос — «когда строку завели». Строка
--     живёт годами: телефон продали, приложение снесли, сотрудник уволился —
--     а created_at всё тот же. Отличить живое устройство от мёртвого было
--     нечем, кроме отказа APNs (DeviceNotRegistered), который приходит не
--     всегда и не сразу.
--   • PushService.upsertToken штампует last_seen_at = now() на ОБОИХ путях —
--     и при первой регистрации, и при повторном подтверждении уже своего
--     токена. Значит «свежесть» строки — факт в таблице, а не догадка.
--   • Это же поле даёт основание для будущей чистки заброшенных токенов
--     (напр. «не видели дольше N месяцев») без риска отключить активный
--     телефон. Саму чистку эта миграция НЕ делает — только заводит факт.
--
-- Порядок операций умышленный: колонку добавляем БЕЗ default, засеваем
-- существующие строки честным created_at (а не моментом деплоя — иначе все
-- давно мёртвые токены разом «оживут» на дату миграции) и только потом ставим
-- DEFAULT now() для будущих вставок.
--
-- Индекс не заводим: обращения к push_tokens идут по user_id (idx_push_tokens_user)
-- и по token (UNIQUE), а last_seen_at — поле для редкого административного
-- прохода по всей таблице, где индекс не нужен.
--
-- Идемпотентно: ADD COLUMN IF NOT EXISTS, UPDATE только по NULL, SET DEFAULT
-- переустанавливает то же значение. Повторный прогон — no-op.
-- ============================================================================

ALTER TABLE push_tokens ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMPTZ;

UPDATE push_tokens
   SET last_seen_at = COALESCE(created_at, now())
 WHERE last_seen_at IS NULL;

ALTER TABLE push_tokens ALTER COLUMN last_seen_at SET DEFAULT now();
