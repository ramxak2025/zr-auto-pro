-- 113_products_unit_bundle_drift.sql
-- ============================================================================
-- Schema-drift свежей установки (найдено НЕЗАВИСИМО двумя проверками на
-- одноразовых базах: волной идемпотентности create-чека и волной RLS).
--
-- В 001_init.sql DO-блоки `ALTER TABLE products ADD COLUMN unit / is_bundle /
-- bundle_items` стоят РАНЬШЕ, чем `CREATE TABLE products`, и глотают
-- undefined_table: на девственной базе, разворачиваемой строго миграциями,
-- этих колонок НЕТ, и POST /products падает 500 (код их пишет/читает).
--
-- Прод НЕ задет — там колонки существуют исторически (были добавлены, когда
-- 001 гонялся по уже созданной схеме). Для прода этот файл — три no-op'а.
-- Править сам 001 нельзя (уже применён и зарегистрирован в _migrations),
-- поэтому выравниваем хвостовой идемпотентной миграцией — теперь чистая
-- установка (стейджинг, throwaway-тесты, второй сервер при восстановлении
-- из offsite-бэкапа) сходится с продом.
--
-- Типы/дефолты зеркалят БАЙТ-В-БАЙТ DO-блоки из 001 (строки 83-85): те же
-- nullable-колонки, те же дефолты 'pcs'/false/'[]' — чтобы чистая установка
-- сошлась с прод-схемой, а не с «улучшенной» версией.
-- ============================================================================

ALTER TABLE products ADD COLUMN IF NOT EXISTS unit TEXT DEFAULT 'pcs';
ALTER TABLE products ADD COLUMN IF NOT EXISTS is_bundle BOOLEAN DEFAULT false;
ALTER TABLE products ADD COLUMN IF NOT EXISTS bundle_items JSONB DEFAULT '[]';
