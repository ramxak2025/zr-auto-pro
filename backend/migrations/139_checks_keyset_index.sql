-- 139_checks_keyset_index.sql
-- Индекс под курсорную пагинацию журнала по ТРОЙКЕ (date, created_at, id).
--
-- ЗАЧЕМ. Журнал в приложении листался по НОМЕРУ страницы (offset). В живом
-- сервисе чеки создаются десятками в день, каждый новый сдвигает ленту на одну
-- позицию — и следующая страница отдаёт уже не то: часть строк ПРОПУСКАЕТСЯ
-- (в списке дыра), часть приходит ДВАЖДЫ (дубль ключа в React → белые и битые
-- ячейки). Плюс 30-секундный опрос перезапрашивал те же номера страниц,
-- которые к тому моменту означали другое. Отсюда жалобы «при скролле чеки
-- исчезают, появляется пустота, потом снова появляются».
--
-- Курсор от вставок не зависит: он указывает на КОНКРЕТНУЮ строку, а не на
-- позицию. Тройка вместо прежней пары (date, id): id — случайный uuid, и пара
-- давала внутри одного дня произвольный порядок вместо «сверху свежие».
-- created_at делает порядок осмысленным, id остаётся финальным разрывателем
-- ничьих — ключ строго уникален, страница не может потерять или продублировать
-- строку.
--
-- Порядок колонок в индексе совпадает с ORDER BY (все DESC) — Postgres идёт
-- по индексу вперёд, без сортировки. Частичный (deleted_at IS NULL): корзина
-- в журнал не входит, а без строк корзины индекс меньше и горячее.
--
-- CONCURRENTLY НЕ используем: MigrationRunner гоняет файл в транзакции, а
-- CREATE INDEX CONCURRENTLY внутри транзакции запрещён. На текущем объёме
-- (крупнейший тенант — меньше тысячи чеков) обычный CREATE INDEX берёт блокировку
-- на доли секунды.
CREATE INDEX IF NOT EXISTS idx_checks_tenant_date_created_id
  ON checks (tenant_id, date DESC, created_at DESC, id DESC)
  WHERE deleted_at IS NULL;
