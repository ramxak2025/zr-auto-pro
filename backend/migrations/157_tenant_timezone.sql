-- ============================================================================
-- Часовой пояс автосервиса.
--
--   • tenants.timezone — IANA-идентификатор пояса тенанта ('Europe/Moscow',
--     'Asia/Yekaterinburg', 'Asia/Vladivostok', …). Владелец выбирает его в
--     «Настройках компании» (PATCH /my-company, ключ company_manage).
--     От пояса зависит, что считается «сегодня»: границы дня/месяца в
--     отчётах, смены и зарплата.
--
--   • DEFAULT 'Europe/Moscow' — ровно то поведение, которое зашито в код
--     сегодня (MSK_OFFSET_MS = UTC+3 в reports/salary/shifts). Поэтому
--     миграция НИЧЕГО не меняет для существующих тенантов: все получают
--     Москву и продолжают видеть те же цифры.
--
--   • Значение валидируется на бэкенде по белому списку российских поясов
--     (backend/src/common/timezone.ts) — в БД это обычный TEXT, потому что
--     список поясов со временем пополняется (новые регионы, СНГ), и
--     CHECK-констрейнт пришлось бы менять миграцией на каждое пополнение.
--     На NULL/мусор в колонке код всё равно падает в Europe/Moscow.
--
-- ADDITIVE и идемпотентно: ADD COLUMN IF NOT EXISTS. Повторный прогон
-- сходится к тому же состоянию. Не редактируется после применения.
-- ============================================================================

ALTER TABLE tenants ADD COLUMN IF NOT EXISTS timezone TEXT NOT NULL DEFAULT 'Europe/Moscow';

-- Страховка для строк, где колонка уже существовала и допускала NULL
-- (например, добавлялась вручную на стенде до этой миграции).
UPDATE tenants SET timezone = 'Europe/Moscow' WHERE timezone IS NULL OR btrim(timezone) = '';
