-- v3.0.1 ФИЧА 1 — «Реальная чистая прибыль (по начислению)»: часть 1 из 2.
--
-- Владелец хочет видеть на главной ГЛАДКУЮ чистую прибыль: аренда/коммуналка/
-- маркетинг/оклады не должны «прыгать» в день фактической оплаты, а размазываться
-- по всем календарным дням месяца (accrual). Эта миграция вводит КОНФИГ плановых
-- ПОСТОЯННЫХ расходов (помесячная сумма по категории) + флаг «повторяющаяся» на
-- категориях расходов — ключ к развязке двойного списания (см. ниже).
--
-- ── Таблица fixed_costs ────────────────────────────────────────────────────
--   Плановый ежемесячный постоянный расход тенанта (аренда, коммуналка,
--   маркетинг, произвольные). monthly_amount — сумма В МЕСЯЦ (RUB). Прибыль по
--   начислению вычитает АМОРТИЗИРОВАННУЮ долю: monthly_amount / дней_в_месяце ×
--   прошедших_дней (MTD) и полную monthly_amount в прогнозе на месяц.
--   Считается ТОЛЬКО active=true. Никакой суммы «по факту» здесь нет — это
--   план/бюджет, а не платёж.
--
-- ── Развязка двойного списания (accrual vs cash) — expense_categories.is_recurring ──
--   ПРАВИЛО (подтверждено владельцем): плановый (повторяющийся) расход
--   размазывается в ПРИБЫЛЬ из этого конфига; его ФАКТИЧЕСКАЯ оплата идёт ТОЛЬКО
--   в «Движение денег» (касса) и в прибыль ВТОРОЙ раз НЕ попадает. Разовый расход
--   (вне плана — купил компрессор) уменьшает прибыль ПО ФАКТУ.
--   Чтобы отличить «оплату планового» от «разового», на категории расходов
--   вводится булев флаг is_recurring:
--     • is_recurring = true  → расходы этой категории — оплата плановой постоянки
--       (аренда/коммуналка/маркетинг/зарплата). В accrual-прибыли они НЕ
--       вычитаются как факт (постоянка уже начислена из fixed_costs +
--       employee_compensation). Видны только в «Движении денег».
--     • is_recurring = false → разовый расход, уменьшает прибыль по факту
--       (прежнее поведение — байт-в-байт).
--   Легаси-категория «Зарплата» и без флага исключалась из прибыли (per-check
--   %мастеру уже в profit, а выплаты — cash-only); эта развязка её обобщает на
--   аренду/коммуналку/маркетинг.
--
--   ВАЖНО: accrual-прибыль (reports v2 dashboard) — новая, гладкая. Кассовый
--   «Финансовый отчёт» (getFinancial, v1) остаётся ПО ФАКТУ и не меняется — это
--   намеренно два разных представления (движение денег ≠ прибыль по начислению).
--
-- ── RLS (зеркало 112) ──────────────────────────────────────────────────────
--   Таблица тенант-скоупная, системных строк нет → одна политика tenant_isolation
--   (USING + WITH CHECK по app.tenant_id). Без DB_APP_PASSWORD (admin-суперпул)
--   политика инертна, как и вся 112; изоляцию всё равно держит WHERE tenant_id
--   в сервисе.
--
-- Идемпотентность: CREATE TABLE/INDEX IF NOT EXISTS, ADD COLUMN IF NOT EXISTS,
-- ENABLE/FORCE RLS идемпотентны, DROP POLICY IF EXISTS + CREATE. Повторный прогон
-- сходится к тому же состоянию. Уже применённый файл НЕ редактируем.
-- ============================================================================

-- ── 1. Плановые постоянные расходы (помесячно) ───────────────────────────────
CREATE TABLE IF NOT EXISTS fixed_costs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id UUID NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  -- Отображаемое имя строки бюджета: «Аренда», «Коммуналка», «Реклама Авито», …
  name TEXT NOT NULL,
  -- Грубая категория для группировки/иконки: 'rent'|'utilities'|'marketing'|'other'.
  -- Не enum (свобода для будущих категорий), нормализуется в сервисе.
  category TEXT NOT NULL DEFAULT 'other',
  -- Сумма В МЕСЯЦ (RUB). NUMERIC(14,2): до ~1e12, копейки. >= 0 гарантирует сервис.
  monthly_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
  -- Пауза без удаления: неактивные строки в прибыль не начисляются.
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Чтение конфига тенанта (активные строки) — единственный горячий путь.
CREATE INDEX IF NOT EXISTS idx_fixed_costs_tenant ON fixed_costs (tenant_id);

ALTER TABLE fixed_costs ENABLE ROW LEVEL SECURITY;
ALTER TABLE fixed_costs FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON fixed_costs;
CREATE POLICY tenant_isolation ON fixed_costs
  USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid)
  WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid);

-- ── 2. Флаг «повторяющаяся» на категориях расходов (развязка двойного счёта) ──
-- Дефолт false → нулевая регрессия: без пометки категория ведёт себя как разовая
-- (расходы уменьшают прибыль по факту, ровно как сегодня). Владелец помечает
-- аренду/коммуналку/маркетинг/зарплату как recurring, чтобы их оплаты перестали
-- резать accrual-прибыль (она уже начислена из конфига).
ALTER TABLE expense_categories ADD COLUMN IF NOT EXISTS is_recurring BOOLEAN NOT NULL DEFAULT false;
