/**
 * ГРАНИЦА ЖИЗНИ СЕССИЙ (users.sessions_valid_from, миграция 165) — ОДНА
 * редакция правила на весь backend.
 *
 * ЧТО ЭТО. Пароль сменили (сам сотрудник — ProfileService.changePassword, либо
 * владелец сбросил — UsersService.update) → в users.sessions_valid_from лёг
 * момент смены. Любой токен, выписанный РАНЬШЕ этого момента, недействителен,
 * сколько бы ни оставалось до его exp. Иначе «сменить пароль, чтобы выгнать
 * чужого» невозможно в принципе: ревокация 021 адресует ОДИН токен по jti, а
 * списка живых jti пользователя не существует.
 *
 * ПОЧЕМУ ФАЙЛ, А НЕ ТРИ КОПИИ SQL. Границу обязаны сверять ТРИ места, и все
 * три — по одному правилу:
 *   • JwtStrategy — каждый запрос (но результат кешируется на 30 секунд, и
 *     кеш внутрипроцессный: в docker-compose реплик backend несколько, у
 *     каждой свой);
 *   • AuthService.refresh      — чеканит СВЕЖИЙ 30-дневный токен;
 *   • AuthService.switchPoint  — чеканит СВЕЖИЙ 30-дневный токен.
 * Две последние ручки ходят в базу МИМО кеша (живая проверка «уволен /
 * деактивирован / удалён»), но границу раньше не сверяли. В окне до истечения
 * чужого кеша вор успевал дёрнуть продление или смену филиала и получить
 * токен, выписанный УЖЕ ПОСЛЕ смены пароля, — такой токен границу проходит
 * законно, и смена пароля переставала выгонять вора совсем. Отставшая копия
 * правила здесь означает ровно эту дыру, поэтому редакция ровно одна.
 *
 * ПОЧЕМУ СРАВНЕНИЕ В БАЗЕ, А НЕ В NODE. Слева — claim `iat` токена, справа —
 * колонка timestamptz, которую пишет now() Postgres. Сравнить их в Node
 * значило бы поставить безопасность в зависимость от расхождения часов Node и
 * Postgres: часы Node вперёд — ложный разлогин всему тенанту, назад — окно,
 * в котором стухший токен проходит.
 */

/** Отказ, который видит человек. Формулировка одна на весь монорепо. */
export const SESSION_STALE_MESSAGE = 'Пароль изменён — войдите заново';

/**
 * SQL-выражение «токен выписан ДО границы» → колонка `session_stale`.
 *
 * `iatParam` — плейсхолдер с claim `iat` токена (секунды, `$3` и т. п.);
 * `userAlias` — алиас таблицы users в запросе вызывающего.
 *
 * FAIL-CLOSED: `iat` не пришёл (NULL) при ВЫСТАВЛЕННОЙ границе → сессия
 * считается стухшей: проверить её возраст нечем. Граница не выставлена (NULL —
 * дефолт колонки, пароль ни разу не меняли) → не стухшая никогда, поэтому
 * обычные сессии эта проверка не трогает.
 */
export function sessionStaleSql(iatParam: string, userAlias = 'u'): string {
  return `(${userAlias}.sessions_valid_from IS NOT NULL
                 AND (${iatParam}::double precision IS NULL
                      OR to_timestamp(${iatParam}::double precision) < ${userAlias}.sessions_valid_from)) as session_stale`;
}

/**
 * Claim `iat` из уже раскодированного токена. Не число (нет claim'а, мусор) →
 * null, и SQL выше отбивает такой токен при выставленной границе.
 */
export function tokenIatOf(claims: Record<string, unknown> | null | undefined): number | null {
  return typeof claims?.iat === 'number' ? claims.iat : null;
}
