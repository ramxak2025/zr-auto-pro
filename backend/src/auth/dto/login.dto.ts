import { IsString, IsNotEmpty, IsOptional, IsBoolean } from 'class-validator';

export class LoginDto {
  @IsString()
  @IsNotEmpty()
  phone!: string;

  @IsString()
  @IsNotEmpty()
  password!: string;

  /**
   * ПРИЗНАК ТОГО, ЧТО КЛИЕНТ УМЕЕТ ВЫБИРАТЬ ФИЛИАЛ (163).
   *
   * Зачем он вообще нужен: в проде стоят сборки 3.5 и 3.6, которые ждут от
   * POST /auth/login токен СРАЗУ. Отдать им ответ со списком филиалов вместо
   * токена — это пустой экран у живого автосервиса. Поэтому второй шаг
   * включается ТОЛЬКО по явному признаку от клиента, а не по догадке
   * (User-Agent, версия, наличие поля в ответе): догадка ошибается молча и
   * ровно один раз — в проде.
   *
   * Признак не влияет ни на что, кроме формы ответа: старый клиент получает
   * филиал, выбранный сервером (последний использованный, иначе основной
   * сервис), новый — список и промежуточный токен.
   *
   * @IsOptional + @IsBoolean: ValidationPipe({ whitelist: true }) вырезает
   * неописанные поля, поэтому без объявления здесь признак просто не доехал бы
   * до сервиса, и новый клиент навсегда остался бы «старым».
   */
  @IsBoolean()
  @IsOptional()
  supportsPointSelect?: boolean;
}
