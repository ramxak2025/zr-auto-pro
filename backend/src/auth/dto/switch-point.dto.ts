import { IsUUID } from 'class-validator';

/**
 * МГНОВЕННАЯ СМЕНА ФИЛИАЛА ЖИВОЙ СЕССИЕЙ (167): POST /auth/switch-point.
 * Пароль здесь не участвует — личность подтверждена живой сессией, которую
 * проверяет JwtAuthGuard; меняется только филиал, и только на тот, к которому
 * у актора уже есть доступ.
 */
export class SwitchPointDto {
  /**
   * Целевой филиал. @IsUUID отбивает мусор ДО сравнения с uuid-колонкой:
   * иначе Postgres ответил бы 22P02, и вместо честного «филиал недоступен»
   * человек получил бы 500 на кнопке переключения.
   *
   * Режима «все филиалы» (pointId = null) здесь нет и быть не может: сессия
   * без филиала рождает денежные строки с point_id = NULL, невидимые в каждом
   * филиальном срезе (см. common/point-scope.ts).
   */
  @IsUUID()
  pointId!: string;
}
