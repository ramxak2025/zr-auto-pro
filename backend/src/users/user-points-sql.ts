/**
 * Филиалы (156/161): «работает ли сотрудник на выбранной точке».
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ КОЛОНКА. У строки графика (schedule_entries)
 * точки НЕТ и не будет — решение владельца: график филиала — это график его
 * КОМАНДЫ, а команда описана назначениями user_points. Отдельная колонка
 * означала бы второй источник правды, который при переводе сотрудника между
 * филиалами немедленно разъезжается с назначениями.
 *
 * ПОЧЕМУ ОБЩИЙ ФРАГМЕНТ. Один и тот же предикат нужен графику (кто в сетке
 * месяца), «кто сейчас на работе», пикеру мастеров в Кассе и адресатам пуша
 * «пришёл/ушёл». Разъехавшиеся копии = мастер виден в пикере филиала, но не
 * виден в его графике (или наоборот), и заказ-наряд оформляется на чужого
 * мастера. Один модуль — один предикат.
 *
 * БЕЗОПАСНЫЙ ДЕФОЛТ (конвенция 156, менять нельзя): сотрудник БЕЗ единого
 * назначения не ограничен ничем и виден на ВСЕХ точках. Так внедрение не
 * ломает команды, которые ещё не расставили людей по филиалам: пустой
 * user_points у всех = поведение байт-в-байт прежнее.
 */

/**
 * SQL-фрагмент « AND (сотрудник не назначен никуда ИЛИ назначен на эту точку)»
 * + push значения точки в `params`. Пустая строка, когда точка не выбрана
 * (режим у тенанта нет филиалов — одноточечный автосервис) — запрос остаётся дословно прежним.
 *
 * @param userAlias  алиас таблицы users в запросе ('u') — берётся `<alias>.id`.
 * @param tenantPh   ГОТОВЫЙ плейсхолдер тенанта в этом же запросе ('$1').
 *                   Это текст кода вызывающего, а не данные, поэтому его
 *                   подстановка в SQL безопасна; сама точка — всегда параметр.
 */
export function assignedToPointSql(
  userAlias: string,
  tenantPh: string,
  pointId: string | null,
  params: unknown[],
): string {
  if (!pointId) return '';
  params.push(pointId);
  const pointPh = `$${params.length}`;
  return (
    ` AND (NOT EXISTS (SELECT 1 FROM user_points up_none` +
    ` WHERE up_none.user_id = ${userAlias}.id AND up_none.tenant_id = ${tenantPh})` +
    ` OR EXISTS (SELECT 1 FROM user_points up_at` +
    ` WHERE up_at.user_id = ${userAlias}.id AND up_at.tenant_id = ${tenantPh} AND up_at.point_id = ${pointPh}))`
  );
}
