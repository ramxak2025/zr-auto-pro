/**
 * Филиалы (мульти-точки, миграции 156 + 160) — ЕДИНЫЙ источник ответа на
 * вопрос «в каком филиале сейчас работает актор и как это ложится в SQL».
 *
 * ПРОДУКТОВОЕ ТРЕБОВАНИЕ ВЛАДЕЛЬЦА: филиал — отдельный автосервис со своей
 * статистикой. Зайдя в филиал, владелец/мастер видит ТОЛЬКО его чеки, деньги,
 * смены и отчёты. Единственное исключение — база клиентов и их история
 * (см. комментарии-«не чинить» в checks.getAll / clients.service / cars.service).
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ МЕТОД СЕРВИСА: фильтр по точке обязан быть
 * ОДИНАКОВЫМ в журнале (checks.service) и в отчётах/движении денег
 * (reports.service). Разъехавшиеся предикаты = drill-down из отчёта не сходится
 * со списком, а это для владельца выглядит как потеря денег. Один модуль —
 * один предикат.
 *
 * ИСТОЧНИК ТОЧКИ — users.current_point_id, приезжающий в акторе прямо из
 * JwtStrategy (см. ValidatedUser.currentPointId): ноль лишних обращений к БД,
 * значение уже лежит в 30-секундном auth-кеше. Переключение филиала
 * (PointsService.switchPoint) инвалидирует этот кеш, иначе до 30 секунд
 * отдавались бы данные СТАРОЙ точки.
 *
 * ЗАПИСЬ ДЕНЕГ — вторая половина этого же модуля (resolvePointForWrite):
 * читаем широко, но пишем ВСЕГДА в конкретный филиал. Обоснование — в
 * докблоке самой функции.
 */
import { BadRequestException, NotFoundException } from '@nestjs/common';

/** Минимальный актор для решения о скоупе филиала. */
export interface PointScopedActor {
  /** users.current_point_id: null = «Все точки» (сводка по сети). */
  currentPointId?: string | null;
}

/**
 * Точка актора либо null.
 *
 * null означает ОТСУТСТВИЕ фильтра — режим «Все точки»:
 *   • одноточечный тенант (точек нет вовсе) — поведение байт-в-байт прежнее;
 *   • владелец, сознательно выбравший сводку по всей сети;
 *   • сотрудник, ещё не выбравший филиал (PointsService.listForTenant
 *     подставит ему единственную доступную точку при первом же GET /points).
 *
 * Строку принимаем только непустую: '' в uuid-сравнении дал бы 22P02 → 500.
 */
export function actorPointId(actor?: PointScopedActor | null): string | null {
  const raw = actor?.currentPointId;
  return typeof raw === 'string' && raw.length > 0 ? raw : null;
}

/**
 * Сегмент ключа кеша под точку.
 *
 * КРИТИЧНО: сегмент ставится СРАЗУ ПОСЛЕ tenantID и НИКОГДА перед ним —
 * инвалидация отчётов (common/reports-cache.ts) чистит по префиксу
 * `reports:<kind>:<tenantID>`, и точка перед тенантом вывела бы ключ
 * из-под этого префикса: чек пробили, а филиал ещё 30 секунд показывает
 * старые цифры.
 */
export function pointCacheSegment(pointId: string | null): string {
  return pointId ?? 'all';
}

/**
 * SQL-фрагмент фильтра по филиалу + push параметра в `params`.
 * Пустая строка, когда точка не выбрана (запрос остаётся прежним дословно).
 *
 * СТРОГОЕ РАВЕНСТВО, а не `(point_id = $n OR point_id IS NULL)`: строка без
 * точки, показанная в КАЖДОМ филиале, задваивала бы деньги при сравнении
 * филиалов между собой. Историю без точки разово прибивает к первой живой
 * точке миграция 160, а новые «ничьи» чеки может родить только актор в режиме
 * «Все точки» — то есть владелец, у которого сетевой срез и так перед глазами.
 * Инвариант: деньги не исчезают (видны в сетевом срезе) и не двоятся.
 *
 * Параметр — ВСЕГДА плейсхолдер: uuid из БД склеивать в SQL нельзя даже
 * «своим» значением.
 */
export function pointFilterSql(alias: string | null, pointId: string | null, params: unknown[]): string {
  if (!pointId) return '';
  params.push(pointId);
  return ` AND ${alias ? `${alias}.` : ''}point_id = $${params.length}`;
}

