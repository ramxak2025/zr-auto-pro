/**
 * Минимальный доступ к БД: подойдёт и пул, и клиент внутри транзакции.
 * Своя структурная сигнатура (а не импорт `pg`) — модуль остаётся без
 * зависимостей и импортируется откуда угодно, включая тесты.
 */
export interface PointScopeQueryable {
  query(text: string, params?: unknown[]): Promise<{ rows: any[] }>;
}

// ФИЛИАЛ ДЕНЕЖНОЙ ЗАПИСИ — ЭТО ФИЛИАЛ СЕССИИ, И БОЛЬШЕ НИЧЕГО (163).
//
// Здесь раньше стоял resolvePointForWrite: он ходил в базу, проверял, жива ли
// точка актора, подставлял единственную доступную и отвечал 400 «Выберите
// филиал», когда доступных несколько. Всё это чинило последствия режима «все
// филиалы» — сессии без филиала. Режима больше нет (инвариант в шапке модуля),
// поэтому:
//   • филиал у денежной записи берётся из актора — actorPointId(actor);
//   • отказ «Выберите филиал» исчез со ВСЕХ путей записи: спрашивать нечего,
//     филиал выбран при входе;
//   • проверка «жива ли точка» переехала в JwtStrategy, где выполняется ОДИН
//     раз на запрос (и кешируется на 30 секунд) вместо одного раза на каждую
//     денежную строку.
//
// Второй копии этого правила в модулях быть не должно: если денежному пути
// нужен филиал — он берёт actorPointId(actor), а не резолвит его сам.

/**
 * Таблицы, у которых есть собственный `point_id` и по которым стоит гейт
 * ЗАПИСИ. Литеральный union, а не свободная строка: имя таблицы уходит в SQL
 * склейкой (плейсхолдером имя объекта не задать), и единственная гарантия
 * безопасности здесь — то, что значение физически не может прийти извне.
 */
export type PointScopedTable =
  | 'checks'
  | 'expenses'
  | 'salary_payouts'
  | 'salary_premiums'
  | 'salary_penalties'
  | 'salary_payments';

/**
 * ГЕЙТ ЗАПИСИ ПО ФИЛИАЛУ: строку ЧУЖОГО филиала изменить нельзя.
 *
 * ЗАЧЕМ. Скоуп филиала резал ЧТЕНИЕ (списки, отчёты, карточки), но мутации
 * адресуются по id и фильтра не имели — асимметрия «читаем узко, пишем
 * широко». Мастер филиала А, зная id, отменял выплату филиала Б, удалял его
 * премию или правил его штраф: в своём срезе он изменения не видит, а деньги
 * ДРУГОГО филиала уже поехали. Для чеков это правило появилось первым
 * (ChecksService.assertCheckPointForWrite), здесь оно вынесено в общий модуль,
 * чтобы предиката существовало РОВНО ОДИН, а не по копии на модуль.
 *
 * ПОВЕДЕНИЕ. Точки у актора нет (у тенанта нет филиалов — одноточечный автосервис) — гейта
 * нет вовсе, запрос остаётся прежним дословно. Точка есть, а строка чужая —
 * 404 с текстом самого объекта: существование чужой строки не подтверждаем
 * (та же конвенция, что в ClientsService/CarsService).
 *
 * БЕЗ фильтра «живости» строки (deleted_at / status): гейт отвечает ровно на
 * один вопрос — «эта строка моего филиала?». Живая она или нет, решают
 * собственные условия вызывающего; дублировать их здесь значило бы получить
 * два разных ответа на один вопрос.
 *
 * ВЫЗЫВАТЬ ДО pool.connect(): гейт делает свой запрос, и вторая коннекция под
 * уже открытой транзакцией на исчерпанном пуле даёт взаимную блокировку.
 */
export async function assertRowPointForWrite(
  db: PointScopeQueryable,
  table: PointScopedTable,
  id: string,
  tenantID: string,
  pointId: string | null,
  notFoundMessage: string,
): Promise<void> {
  if (!pointId) return;
  const params: unknown[] = [id, tenantID];
  const filter = pointFilterSql('t', pointId, params);
  const { rows } = await db.query(`SELECT 1 FROM ${table} t WHERE t.id = $1 AND t.tenant_id = $2${filter}`, params);
  if (rows.length === 0) throw new NotFoundException({ message: notFoundMessage });
}
