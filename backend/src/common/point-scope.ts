/**
 * Минимальный доступ к БД: подойдёт и пул, и клиент внутри транзакции.
 * Своя структурная сигнатура (а не импорт `pg`) — модуль остаётся без
 * зависимостей и импортируется откуда угодно, включая тесты.
 */
export interface PointScopeQueryable {
  query(text: string, params?: unknown[]): Promise<{ rows: any[] }>;
}

/** Актор денежной ЗАПИСИ: тенант, сам пользователь и его текущая точка. */
export interface PointWriteActor extends PointScopedActor {
  tenantID: string;
  /**
   * Автор записи. null допустим: часть складских путей знает только тенанта
   * (системная операция без пользователя). В SQL ниже `up.user_id = $2` с NULL
   * — валидное сравнение, дающее «назначений нет», то есть безопасную ветку
   * «все живые точки тенанта». Пустая строка вместо NULL дала бы 22P02 на
   * uuid-сравнении, поэтому именно null, а не `?? ''`.
   */
  userID: string | null;
}

/**
 * ЕДИНОЕ ПРАВИЛО ФИЛИАЛА ДЛЯ ДЕНЕЖНОЙ ЗАПИСИ. Возвращает точку, которой
 * штампуется новая денежная строка, либо бросает 400.
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ. Чтение в режиме «Все точки» (current_point_id = NULL)
 * фильтра не применяет — и это правильно: владелец видит сводку по сети.
 * Но ЗАПИСЬ в том же режиме рождала строку с point_id = NULL, а филиальные
 * срезы фильтруют СТРОГИМ равенством (см. pointFilterSql выше). Такую строку
 * не видел НИ ОДИН филиал:
 *   • чек выпадал из журнала филиала, из его Z-отчёта и из карточки «Филиалы»;
 *   • выплата зарплаты не вычиталась из «к выплате» ни в одном филиале —
 *     владелец, глядя на филиальный экран, выдавал её ВТОРОЙ РАЗ.
 * Гейт был только у кассовой смены; асимметрия «читаем широко, пишем в никуда»
 * и была дырой. Теперь правило одно и живёт в одном месте.
 *
 * КАК РЕЗОЛВИМ:
 *   1. Есть текущая точка актора И она ЕЩЁ ЖИВАЯ — она и есть ответ.
 *      Проверка is_active обязательна: точку архивируют «на ходу», а актор
 *      узнаёт об этом только со следующим логином/сбросом кеша. Без проверки
 *      деньги продолжали бы штамповаться в АРХИВНЫЙ филиал — а он не входит
 *      ни в один живой срез (пикер, сводка «Филиалы», списки филиалов их не
 *      показывают), то есть выручка исчезала бы ровно так же, как при
 *      point_id = NULL. Один индексный поиск по PK на денежную запись —
 *      честная цена за то, чтобы деньги не проваливались в архив.
 *   2. Точки нет (или она заархивирована), но актору доступна РОВНО ОДНА живая
 *      точка — молча подставляем её. Мастер, приписанный к одному филиалу,
 *      вопроса не видит.
 *   3. Доступных несколько — 400 «Выберите филиал, …»: угадывать, за чей счёт
 *      прошли деньги, нельзя, это ошибка учёта, а не удобство.
 *   4. У тенанта живых точек НЕТ ВОВСЕ — возвращаем null, как раньше.
 *      Одноточечный автосервис не должен заметить этой волны вообще.
 *
 * ЧТО СЧИТАЕТСЯ «ДОСТУПНОЙ» ТОЧКОЙ — та же конвенция 156, что у чтения:
 * есть назначения (user_points) на живые точки — только они; назначений на
 * живые точки нет — все живые точки тенанта. Вторая ветка закрывает и случай
 * «сотрудник назначен только на заархивированный филиал»: иначе он не смог бы
 * провести ни одного чека и при этом не смог бы выбрать точку (switchPoint
 * пускает только на назначенные) — тупик на ровном месте.
 *
 * ФОРМА ОШИБКИ — та же, что у кассовой смены с самого начала: HTTP 400 и
 * `{ message: 'Выберите филиал, …' }`. Клиенты (mobile/web) уже показывают
 * message как есть, поэтому новые денежные гейты не требуют правок на
 * клиентах: текст различается только хвостом-целью.
 *
 * @param purpose хвост сообщения в винительном значении цели, например
 *                'чтобы пробить чек' → «Выберите филиал, чтобы пробить чек».
 */
export async function resolvePointForWrite(
  db: PointScopeQueryable,
  actor: PointWriteActor,
  purpose: string,
): Promise<string | null> {
  const current = actorPointId(actor);
  if (current) {
    const { rows: live } = await db.query(
      `SELECT 1 FROM tenant_points WHERE id = $1 AND tenant_id = $2 AND is_active = true`,
      [current, actor.tenantID],
    );
    if (live.length > 0) return current;
    // Точка заархивирована, пока актор был «в ней» — падаем в общий резолв
    // ниже: он подставит единственную живую точку либо честно спросит, какую
    // выбрать. Молчаливого возврата в архив здесь быть не может.
  }

  // LIMIT 2 — больше и не нужно: вопрос «одна или больше одной». Порядок
  // (sort_order → created_at → id) совпадает с пикером точек и с миграциями
  // 160/161, поэтому «единственная» точка резолвится детерминированно.
  const { rows } = await db.query(
    `WITH live AS (
       SELECT p.id, p.sort_order, p.created_at
         FROM tenant_points p
        WHERE p.tenant_id = $1 AND p.is_active = true
     ),
     mine AS (
       SELECT l.* FROM live l
        WHERE EXISTS (SELECT 1 FROM user_points up
                       WHERE up.point_id = l.id AND up.user_id = $2 AND up.tenant_id = $1)
     )
     SELECT id FROM (
       SELECT * FROM mine
       UNION ALL
       SELECT * FROM live WHERE NOT EXISTS (SELECT 1 FROM mine)
     ) available
      ORDER BY sort_order ASC, created_at ASC, id ASC
      LIMIT 2`,
    [actor.tenantID, actor.userID],
  );

  // Точек нет вовсе → NULL, поведение одноточечного тенанта байт-в-байт прежнее.
  if (rows.length === 0) return null;
  if (rows.length === 1) return rows[0].id as string;
  throw new BadRequestException({ message: `Выберите филиал, ${purpose}` });
}

/**
 * Таблицы, у которых есть собственный `point_id` и по которым стоит гейт
 * ЗАПИСИ. Литеральный union, а не свободная строка: имя таблицы уходит в SQL
 * склейкой (плейсхолдером имя объекта не задать), и единственная гарантия
 * безопасности здесь — то, что значение физически не может прийти извне.
 */
export type PointScopedTable =
  | 'checks'
  | 'expenses'
  | 'salary_payouts'
  | 'salary_premiums'
  | 'salary_penalties'
  | 'salary_payments';

/**
 * ГЕЙТ ЗАПИСИ ПО ФИЛИАЛУ: строку ЧУЖОГО филиала изменить нельзя.
 *
 * ЗАЧЕМ. Скоуп филиала резал ЧТЕНИЕ (списки, отчёты, карточки), но мутации
 * адресуются по id и фильтра не имели — асимметрия «читаем узко, пишем
 * широко». Мастер филиала А, зная id, отменял выплату филиала Б, удалял его
 * премию или правил его штраф: в своём срезе он изменения не видит, а деньги
 * ДРУГОГО филиала уже поехали. Для чеков это правило появилось первым
 * (ChecksService.assertCheckPointForWrite), здесь оно вынесено в общий модуль,
 * чтобы предиката существовало РОВНО ОДИН, а не по копии на модуль.
 *
 * ПОВЕДЕНИЕ. Точки у актора нет («Все точки» / одноточечный тенант) — гейта
 * нет вовсе, запрос остаётся прежним дословно. Точка есть, а строка чужая —
 * 404 с текстом самого объекта: существование чужой строки не подтверждаем
 * (та же конвенция, что в ClientsService/CarsService).
 *
 * БЕЗ фильтра «живости» строки (deleted_at / status): гейт отвечает ровно на
 * один вопрос — «эта строка моего филиала?». Живая она или нет, решают
 * собственные условия вызывающего; дублировать их здесь значило бы получить
 * два разных ответа на один вопрос.
 *
 * ВЫЗЫВАТЬ ДО pool.connect(): гейт делает свой запрос, и вторая коннекция под
 * уже открытой транзакцией на исчерпанном пуле даёт взаимную блокировку.
 */
export async function assertRowPointForWrite(
  db: PointScopeQueryable,
  table: PointScopedTable,
  id: string,
  tenantID: string,
  pointId: string | null,
  notFoundMessage: string,
): Promise<void> {
  if (!pointId) return;
  const params: unknown[] = [id, tenantID];
  const filter = pointFilterSql('t', pointId, params);
  const { rows } = await db.query(`SELECT 1 FROM ${table} t WHERE t.id = $1 AND t.tenant_id = $2${filter}`, params);
  if (rows.length === 0) throw new NotFoundException({ message: notFoundMessage });
}
