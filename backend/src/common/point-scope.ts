/**
 * Филиалы (мульти-точки, миграции 156 + 160 + 163) — ЕДИНЫЙ источник ответа на
 * вопрос «в каком филиале сейчас работает актор и как это ложится в SQL».
 *
 * ПРОДУКТОВОЕ ТРЕБОВАНИЕ ВЛАДЕЛЬЦА: филиал — отдельный автосервис со своей
 * статистикой. Зайдя в филиал, владелец/мастер видит ТОЛЬКО его чеки, деньги,
 * смены и отчёты. Единственное исключение — база клиентов и их история
 * (см. комментарии-«не чинить» в checks.getAll / clients.service / cars.service).
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ МЕТОД СЕРВИСА: фильтр по точке обязан быть
 * ОДИНАКОВЫМ в журнале (checks.service) и в отчётах/движении денег
 * (reports.service). Разъехавшиеся предикаты = drill-down из отчёта не сходится
 * со списком, а это для владельца выглядит как потеря денег. Один модуль —
 * один предикат.
 *
 * ИСТОЧНИК ФИЛИАЛА — ТОКЕН СЕССИИ (163). Филиал выбирается при входе, едет
 * claim'ом `pointId` и живёт ровно столько, сколько живёт сессия; JwtStrategy
 * кладёт его в актор (ValidatedUser.currentPointId) тем же запросом, что роль
 * и права. До 163 филиал лежал в users.current_point_id — одной колонке на все
 * устройства человека, — и переключение на телефоне молча уводило веб-сессию в
 * другой автосервис. Сменить филиал теперь можно только выходом и новым входом.
 *
 * ГЛАВНОЕ СЛЕДСТВИЕ ДЛЯ ДЕНЕГ — ИНВАРИАНТ, НА КОТОРОМ ДЕРЖИТСЯ ВЕСЬ МОДУЛЬ:
 *
 *     филиал актора = null  ⟺  у тенанта НЕТ НИ ОДНОГО ЖИВОГО ФИЛИАЛА
 *
 * Рабочего режима «все филиалы» больше не существует. Держит инвариант
 * JwtStrategy: токен без филиала (старая сборка, сессия до 163, филиал у
 * тенанта появился уже после входа) получает подставленный сервером
 * (autexa_default_point), а токен с филиалом, который заархивировали или у
 * которого сняли доступ, получает 401 и вход заново.
 *
 * ЗАЧЕМ ЭТОТ ИНВАРИАНТ БЫЛ НУЖЕН. Раньше чтение в режиме «все филиалы» фильтра
 * не применяло, а ЗАПИСЬ в том же режиме рождала строку с point_id = NULL —
 * и её не видел НИ ОДИН филиал (срезы фильтруют строгим равенством, см.
 * pointFilterSql):
 *   • чек выпадал из журнала филиала, из его Z-отчёта и из карточки «Филиалы»;
 *   • выплата зарплаты не вычиталась из «к выплате» ни в одном филиале —
 *     владелец, глядя на филиальный экран, выдавал её ВТОРОЙ РАЗ.
 * Прежнее лекарство (resolvePointForWrite: «своя точка, либо единственная
 * доступная, либо 400 „Выберите филиал“») удалено вместе с болезнью: филиал
 * денежной записи — это просто филиал сессии, спрашивать больше нечего и
 * отказывать не в чем. Денежные пути берут его через actorPointId(actor).
 */
import { NotFoundException } from '@nestjs/common';

/** Минимальный актор для решения о скоупе филиала. */
export interface PointScopedActor {
  /** Филиал СЕССИИ (claim `pointId` токена, 163). null = у тенанта нет филиалов. */
  currentPointId?: string | null;
}

/**
 * Филиал сессии либо null.
 *
 * null означает ОТСУТСТВИЕ фильтра и, по инварианту 163 (см. шапку модуля),
 * ровно один случай: у тенанта нет ни одного живого филиала — одноточечный
 * автосервис, поведение байт-в-байт прежнее.
 *
 * Строку принимаем только непустую: '' в uuid-сравнении дал бы 22P02 → 500.
 */
export function actorPointId(actor?: PointScopedActor | null): string | null {
  const raw = actor?.currentPointId;
  return typeof raw === 'string' && raw.length > 0 ? raw : null;
}

/**
 * Сегмент ключа кеша под точку.
 *
 * КРИТИЧНО: сегмент ставится СРАЗУ ПОСЛЕ tenantID и НИКОГДА перед ним —
 * инвалидация отчётов (common/reports-cache.ts) чистит по префиксу
 * `reports:<kind>:<tenantID>`, и точка перед тенантом вывела бы ключ
 * из-под этого префикса: чек пробили, а филиал ещё 30 секунд показывает
 * старые цифры.
 */
export function pointCacheSegment(pointId: string | null): string {
  return pointId ?? 'all';
}

/**
 * SQL-фрагмент фильтра по филиалу + push параметра в `params`.
 * Пустая строка, когда точка не выбрана (запрос остаётся прежним дословно).
 *
 * СТРОГОЕ РАВЕНСТВО, а не `(point_id = $n OR point_id IS NULL)`: строка без
 * точки, показанная в КАЖДОМ филиале, задваивала бы деньги при сравнении
 * филиалов между собой. Историю без точки разово прибивает к ОСНОВНОМУ
 * сервису тенанта (tenant_points.is_main) миграция 160 — филиал, открытый
 * позже, чужую историю не забирает. НОВЫХ строк без филиала у тенанта с
 * филиалами больше не появляется вовсе: филиал есть у каждой сессии (163),
 * а значит и у каждой денежной записи. Инвариант: деньги не двоятся и не
 * проваливаются мимо всех филиалов.
 *
 * Параметр — ВСЕГДА плейсхолдер: uuid из БД склеивать в SQL нельзя даже
 * «своим» значением.
 */
export function pointFilterSql(alias: string | null, pointId: string | null, params: unknown[]): string {
  if (!pointId) return '';
  params.push(pointId);
  return ` AND ${alias ? `${alias}.` : ''}point_id = $${params.length}`;
}

