/**
 * ПРЕМИИ И МОТИВАЦИЯ В ПРИБЫЛИ — один источник правила для всех отчётов.
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. Зарплата попадает в прибыль ДВАЖДЫ описанным
 * правилом, и оба его конца живут в коде:
 *   • НАЧИСЛЕНИЕ режет прибыль — service_salary_total + product_salary_total
 *     запечены в самой строке чека и сидят внутри checks.profit;
 *   • ВЫПЛАТА прибыль НЕ режет — зеркальный расход выплаты лежит в категории
 *     «Зарплата», и отчёты исключают её ПО ИМЕНИ, иначе труд списался бы
 *     дважды.
 *
 * Премия деньгами (salary_premiums.type='cash') и мотивация
 * (motivation_accruals.amount) — тоже НАЧИСЛЕНИЯ: salary.getAll кладёт их в
 * totalEarnings, они увеличивают долг перед мастером и выдаются той же
 * выплатой. Но в чековые колонки они не попадают (мотивация — отдельная
 * таблица, премия — решение владельца вне чека), а выплата исключена по имени
 * категории. Итог до этой правки: реальные деньги, выданные мастерам, не
 * уменьшали прибыль НИГДЕ — владелец видел прибыль выше фактической ровно на
 * сумму премий и мотивации и принимал по ней решения.
 *
 * ПОЧЕМУ ВЫЧИТАЕМ, А НЕ ПОКАЗЫВАЕМ СПРАВОЧНОЙ СТРОКОЙ. Это не «ещё один
 * взгляд» на те же деньги, а третий вид начисления зарплаты рядом с двумя
 * существующими. Справочная строка оставила бы прибыль завышенной — то есть
 * оставила бы ровно тот дефект, ради которого правило и пишется. Строку при
 * этом тоже отдаём (`premiums` / `motivation` в финотчёте), чтобы владелец
 * видел, из чего сложилась разница, — но netProfit уменьшен.
 *
 * ДВОЙНОГО СЧЁТА НЕТ — проверено по всем трём путям:
 *   • rate_bonus-премия (процент к ставке) сюда НЕ входит: она меняет ставку,
 *     по которой чек запекает salary_amount, и уже сидит в checks.profit;
 *   • мотивация начисляется отдельной таблицей и в product_salary_total не
 *     входит (checks.accrueMotivationPromos — «ADDITIVE ... salary output stays
 *     byte-identical»);
 *   • выплата премии/мотивации уходит в категорию «Зарплата», которую все
 *     расходные запросы отчётов уже исключают.
 *
 * ФИЛИАЛ. У премии своя колонка point_id (161). У мотивации своей точки нет и
 * не нужно: строка рождается из товара В ЧЕКЕ, поэтому филиал берётся у чека —
 * тем же предикатом, что в salary.getAll и salary.getEmployeeMonth.
 *
 * ПОТРЕБИТЕЛИ ПРАВИЛА (держать список полным — разъехавшиеся экраны владелец
 * читает как пропавшие деньги):
 *   • reports.getFinancial            — «Отчёт о прибыли», вычитает + показывает строками;
 *   • reports.computeDashboardV2      — netProfitToday/Month, accrual-прибыль и прогноз;
 *   • points.summaryForTenant         — «Прибыль за месяц» на карточке филиала.
 *     ПЕРЕВЕДЕНА: карточка вычитает премии и мотивацию тем же правилом, через
 *     premiumsByPointMonthSql / motivationByPointMonthSql ниже. До этого она
 *     показывала прибыль БЕЗ них, то есть ВЫШЕ главной, и владелец видел на
 *     соседних экранах два разных числа под одним названием.
 */

/**
 * Месяц отнесения премии: НАЗНАЧЕННЫЙ период, иначе месяц факта в поясе
 * тенанта. Дословное зеркало SalaryService.premiumMonthExpr — «за какой месяц
 * премия» обязано отвечать одинаково в зарплате и в прибыли, иначе премия «за
 * июль», выданная в августе, срежет в отчёте один месяц, а в зарплате другой.
 *
 * `tzPh` — ГОТОВЫЙ плейсхолдер пояса в том же запросе ('$4::text'); это текст
 * кода вызывающего, а не данные.
 */
export function premiumMonthExpr(alias: string, tzPh: string): string {
  return (
    `COALESCE(CASE WHEN ${alias}.period_month_year ~ '^\\d{4}-\\d{2}$' THEN ${alias}.period_month_year END, ` +
    `to_char(${alias}.created_at AT TIME ZONE ${tzPh}, 'YYYY-MM'))`
  );
}

/**
 * Денежная часть премии: только type='cash'. rate_bonus — процент к ставке,
 * он уже запечён в зарплатные колонки чеков (см. шапку модуля), и вычесть его
 * здесь значило бы списать один и тот же труд дважды.
 */
export function premiumCashAmountExpr(alias: string): string {
  return `CASE WHEN ${alias}.type = 'cash' THEN COALESCE(${alias}.amount, 0) ELSE 0 END`;
}

/**
 * Фильтр филиала для мотивации — ЧЕРЕЗ ЧЕК (motivation_accruals.check_id
 * NOT NULL, миграция 095). EXISTS, а не JOIN: без выбранной точки запрос
 * остаётся дословно прежним, а JOIN размножил бы строки.
 *
 * @param alias    алиас motivation_accruals в запросе ('ma').
 * @param tenantPh готовый плейсхолдер тенанта ('$1').
 */
export function motivationPointFilterSql(
  alias: string,
  tenantPh: string,
  pointId: string | null,
  params: unknown[],
): string {
  if (!pointId) return '';
  params.push(pointId);
  return (
    ` AND EXISTS (SELECT 1 FROM checks mch WHERE mch.id = ${alias}.check_id` +
    ` AND mch.tenant_id = ${tenantPh} AND mch.point_id = $${params.length})`
  );
}

// ─────────────────────────────────────────────────────────────────────────────
// ТЕ ЖЕ ПРЕМИИ И МОТИВАЦИЯ, НО СРАЗУ ПО ВСЕМ ФИЛИАЛАМ (сводка «Филиалы»)
// ─────────────────────────────────────────────────────────────────────────────
//
// ЗАЧЕМ ОТДЕЛЬНАЯ ФОРМА. Отчёты считают один филиал за запрос (фильтр
// `point_id = $n`), а карточкам раздела «Филиалы» нужны ВСЕ точки тенанта
// разом — фильтр превращается в GROUP BY. Меняется только это: месяц отнесения
// премии (premiumMonthExpr), денежная часть премии (premiumCashAmountExpr) и
// правило «филиал мотивации = филиал её чека» берутся здесь же, из одного
// модуля. Скопировать их в points.service значило бы завести четвёртую копию
// правила — ровно тот дефект, ради которого этот модуль и существует.
//
// ПОЧЕМУ ЗАПРОСЫ ЦЕЛИКОМ, А НЕ ФРАГМЕНТЫ. Совпадение «прибыль на карточке
// филиала = прибыль на главной» держится не только на выражениях, но и на
// СОСТАВЕ строк (какие премии вообще попали в месяц). Отдав фрагменты, мы бы
// разрешили вызывающему собрать вокруг них другой WHERE — и числа разъехались
// бы снова, просто тише.

/**
 * Премии деньгами за месяц, сгруппированные по филиалу.
 *
 * Плейсхолдеры (порядок фиксирован, вызывающий обязан передать ровно их):
 *   $1 — tenant_id;
 *   $2 — месяц 'YYYY-MM' в поясе тенанта (тот же ключ, что curYm дашборда);
 *   $3 — часовой пояс тенанта.
 *
 * `sp.point_id IS NOT NULL` — премия без филиала не принадлежит ни одной
 * карточке, и раздать её каждой (или всем поровну) значило бы выдумать деньги.
 * Таких строк у тенанта с филиалами не остаётся: их разобрала атрибуция 161/162,
 * а новые пишутся уже с филиалом сессии (163).
 */
export function premiumsByPointMonthSql(): string {
  return `SELECT sp.point_id, COALESCE(SUM(${premiumCashAmountExpr('sp')}), 0) AS total
            FROM salary_premiums sp
           WHERE sp.tenant_id = $1
             AND ${premiumMonthExpr('sp', '$3::text')} = $2
             AND sp.point_id IS NOT NULL
           GROUP BY sp.point_id`;
}

/**
 * Мотивация за месяц, сгруппированная по филиалу.
 *
 * Плейсхолдеры:
 *   $1 — tenant_id;
 *   $2 — начало месяца как UTC-инстант (то же значение, что monthStart
 *        дашборда: у мотивации назначенного периода нет, только accrued_at).
 *
 * ФИЛИАЛ БЕРЁТСЯ У ЧЕКА — то же правило, что в motivationPointFilterSql выше,
 * только в форме JOIN: группировать по значению, которого у самой строки нет,
 * иначе нечем. JOIN не размножает строки — motivation_accruals.check_id
 * NOT NULL и ссылается ровно на один чек (миграция 095).
 */
export function motivationByPointMonthSql(): string {
  return `SELECT mch.point_id, COALESCE(SUM(ma.amount), 0) AS total
            FROM motivation_accruals ma
            JOIN checks mch ON mch.id = ma.check_id AND mch.tenant_id = ma.tenant_id
           WHERE ma.tenant_id = $1
             AND ma.accrued_at >= $2
             AND mch.point_id IS NOT NULL
           GROUP BY mch.point_id`;
}
