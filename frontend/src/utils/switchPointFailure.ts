/**
 * ОТКАЗЫ МГНОВЕННОЙ СМЕНЫ ФИЛИАЛА — чистые правила (167).
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ ВЕТКИ ВНУТРИ ЭКРАНА. У POST /auth/switch-point
 * отказы разного КЛАССА, и у каждого свой единственно правильный исход:
 *
 *   • 403 — это ПРАВИЛО, а не сбой. «Мгновенное переключение доступно только
 *     руководителю», «Филиал недоступен», «Сессия входа под пользователем не
 *     переключает филиал». Сессия ЖИВА: гасить её здесь значит выкинуть
 *     человека из работающего приложения за то, что он нажал не свою кнопку;
 *   • 401 — сессия действительно недействительна (токен отозван, аккаунт
 *     уволен или деактивирован). Второй попытки у неё нет: нужен полноценный
 *     вход, иначе человек останется на экранах, где ни одна цифра не обновится;
 *   • сети нет / 5xx / 429 — ничего не произошло, прежний токен цел, повтор
 *     законен.
 *
 * Ошибиться здесь — значит либо разлогинить руководителя на ровном месте, либо
 * оставить его в мёртвой сессии. Поэтому правило вынесено в чистую функцию и
 * читается целиком, а не собирается из веток по экрану.
 *
 * ТЕКСТ СЕРВЕРА ПРЕДПОЧТИТЕЛЬНЕЕ СВОЕГО: он называет причину («Филиал
 * недоступен», «Аккаунт уволен») и прямо говорит, что делать. Свой текст — когда
 * сервер промолчал или ответил не человеку, а программисту (см. 400).
 */
import { apiErrorMessage, apiErrorStatus } from '../../../shared/utils/apiError';

export interface SwitchPointFailure {
  /**
   * • `relogin` — сессия мертва: увести на вход, показав причину;
   * • `refresh` — остаться в сессии, но перезапросить список филиалов и профиль
   *   (доступ или права изменились, пока человек смотрел на экран);
   * • `stay`    — ничего не менять, повтор разрешён.
   */
  action: 'relogin' | 'refresh' | 'stay';
  /** Что показать человеку. Дословный текст сервера, если он есть. */
  message: string;
}

/**
 * ПРИЧИНА + ЧТО ДЕЛАТЬ для мёртвой сессии. Тексты сервера в этом классе отказов
 * короткие и не всегда договаривают: «Токен отозван» человеку за стойкой не
 * объясняет ничего. Причину берём у сервера, а действие дописываем сами — но
 * только если сервер его уже не назвал, иначе выйдет «войдите заново. Войдите
 * заново», и текст начнут пролистывать не читая.
 */
function reloginMessage(serverMessage: string | null): string {
  if (!serverMessage) return 'Сессия завершена — войдите заново.';
  if (/войдите/i.test(serverMessage)) return serverMessage;
  return `${serverMessage.replace(/\.$/, '')} — войдите заново.`;
}

export function resolveSwitchPointFailure(err: unknown): SwitchPointFailure {
  const status = apiErrorStatus(err);
  const serverMessage = apiErrorMessage(err);

  // Ответа нет вовсе — связь. Сессия цела, филиал не менялся: пусть жмёт ещё раз.
  if (status === null) {
    return {
      action: 'stay',
      message: 'Нет связи с сервером. Проверьте подключение и попробуйте ещё раз.',
    };
  }

  // 401 — токен отозван, аккаунт уволен или деактивирован. Единственный выход —
  // полноценный вход. Причину показываем на экране входа, иначе человек
  // прочитает это как поломку приложения.
  if (status === 401) {
    return {
      action: 'relogin',
      message: reloginMessage(serverMessage),
    };
  }

  // 403 — правило сервера. Сессию НЕ трогаем. Список филиалов и профиль
  // перезапрашиваем: чаще всего отказ означает, что доступ к филиалу сняли или
  // право управления персоналом забрали прямо сейчас, и интерфейс обязан
  // перестать предлагать действие, которое больше не разрешено.
  if (status === 403) {
    return {
      action: 'refresh',
      message: serverMessage ?? 'Филиал недоступен.',
    };
  }

  // 429 — общий write-бакет. Через минуту всё получится, менять нечего.
  if (status === 429) {
    return {
      action: 'stay',
      message: serverMessage ?? 'Слишком много запросов. Подождите минуту и попробуйте ещё раз.',
    };
  }

  // 400 — филиал прислан неверно (не uuid). Из интерфейса это недостижимо, а
  // значит это наша ошибка, и текст сервера здесь НЕ показываем: ValidationPipe
  // отвечает англоязычным «pointId must be a UUID», и владелец автосервиса из
  // него ничего не поймёт. Список филиалов перечитываем — вдруг он устарел.
  if (status === 400) {
    return {
      action: 'refresh',
      message: 'Не удалось перейти в этот филиал. Обновите страницу и попробуйте ещё раз.',
    };
  }

  // 5xx и всё прочее: сервер жив, но сейчас не отвечает по делу. Сессия цела.
  return {
    action: 'stay',
    message: serverMessage ?? `Сервер вернул код ${status}. Попробуйте ещё раз.`,
  };
}
