/**
 * ТОКЕН СЕССИИ ЭТОЙ ВКЛАДКИ — единственная точка записи, чтения и стирания
 * (мгновенная смена филиала 167).
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ. Токен лежит в localStorage, а localStorage ОБЩИЙ на
 * все вкладки браузера. Пока филиал выбирался только при входе, это ничего не
 * ломало: во всех вкладках жила одна и та же сессия одного филиала. С
 * мгновенным переключением (167) руководитель нажимает «перейти» в одной
 * вкладке — и вторая, ничего не заметив, начинает отправлять запросы уже НОВЫМ
 * токеном, продолжая показывать цифры ПРЕЖНЕГО филиала: человек читает
 * заголовок «ТопГаз», а чек уходит в «ZR AUTO». Это ровно тот класс ошибок, из
 * которого и делалась вся волна про филиалы.
 *
 * Поэтому вкладка помнит, каким токеном живёт ОНА, и умеет сравнить его с тем,
 * что лежит в хранилище сейчас (см. {@link inspectStoredSession}):
 *   • совпали — всё нормально;
 *   • в хранилище ЧУЖОЙ токен — сессию перевыпустили в другой вкладке: запросы
 *     этой вкладки не отправляются вовсе (api/axios.ts), а поверх экрана встаёт
 *     объяснение с единственным действием «обновить» (SessionTakeoverGuard);
 *   • в хранилище ПУСТО — в другой вкладке вышли из аккаунта, и наш токен
 *     сервер уже отозвал: сессии больше нет.
 *
 * ПОЧЕМУ СТИРАЕМ ТОЛЬКО СВОЙ ТОКЕН ({@link clearOwnSessionToken}). Вкладка, у
 * которой в хранилище уже чужой токен, не вправе его удалять: там ЖИВАЯ сессия
 * соседней вкладки, в которой человек прямо сейчас работает. Стереть её — это
 * обесточить его посреди заказ-наряда чужими руками.
 */

/** Ключ localStorage. Один на всё приложение — исторический, менять нельзя. */
export const SESSION_TOKEN_KEY = 'token';

/**
 * Токен, которым живёт ИМЕННО ЭТА вкладка. Инициализируется тем, что лежит в
 * хранилище на момент загрузки: это и есть сессия, которую вкладка восстановит
 * через /auth/me.
 */
let activeToken: string | null = readStoredToken();

/** Токен из общего хранилища. Доступ обёрнут: приватный режим умеет бросать. */
export function readStoredToken(): string | null {
  try {
    const value = localStorage.getItem(SESSION_TOKEN_KEY);
    return value && value.trim() ? value : null;
  } catch {
    return null;
  }
}

/**
 * Хранилище не принимает запись (приватный режим, политика браузера, квота).
 * Тогда сравнивать «наш токен» с «тем, что лежит» бессмысленно: там никогда
 * ничего не лежит. Без этого признака вкладка приняла бы собственную неудачную
 * запись за «в другой вкладке вышли» и выбросила бы человека на экран входа
 * сразу после успешного ввода пароля.
 */
let storageUnavailable = false;

/**
 * Записать токен новой сессии — вход, второй шаг входа, смена филиала (167),
 * вход под владельцем. Вкладка с этого момента живёт им.
 */
export function writeSessionToken(token: string): void {
  activeToken = token;
  try {
    localStorage.setItem(SESSION_TOKEN_KEY, token);
    // Проверяем чтением: часть браузеров молча не сохраняет запись, не бросая
    // исключения, и «успешный» setItem ещё ничего не доказывает.
    storageUnavailable = readStoredToken() !== token;
  } catch {
    // Хранилище недоступно — сессия живёт до перезагрузки вкладки. Прервать
    // вход из-за этого нельзя: человек уже подтвердил пароль.
    storageUnavailable = true;
  }
}

/**
 * Стереть токен, ЕСЛИ в хранилище всё ещё лежит наш. Чужой (его положила
 * соседняя вкладка, перевыпустив сессию) не трогаем — см. шапку модуля.
 */
export function clearOwnSessionToken(): void {
  const stored = readStoredToken();
  if (stored === null || stored === activeToken) {
    try {
      localStorage.removeItem(SESSION_TOKEN_KEY);
    } catch {
      // См. комментарий выше.
    }
  }
  activeToken = null;
}

/**
 * Состояние общего хранилища ГЛАЗАМИ ЭТОЙ ВКЛАДКИ:
 *   • `anonymous` — вкладка сессией не живёт (экран входа, лендинг);
 *   • `own`       — в хранилище наш токен, всё нормально;
 *   • `foreign`   — сессию перевыпустили в другой вкладке (смена филиала 167
 *                   или вход под другим аккаунтом): наши экраны показывают
 *                   прежний филиал, работать в них нельзя;
 *   • `gone`      — в другой вкладке вышли из аккаунта, токена больше нет.
 */
export type StoredSessionState = 'anonymous' | 'own' | 'foreign' | 'gone';

export function inspectStoredSession(): StoredSessionState {
  if (activeToken === null) return 'anonymous';
  // Хранилище не работает — сессия живёт только в памяти этой вкладки, других
  // вкладок у неё в принципе нет. Сравнивать не с чем, всё «своё».
  if (storageUnavailable) return 'own';
  const stored = readStoredToken();
  if (stored === activeToken) return 'own';
  if (stored === null) return 'gone';
  return 'foreign';
}

/** Машинный признак отказа «сессию перевыпустили в другой вкладке». */
const SESSION_TAKEOVER_CODE = 'AUTEXA_SESSION_TAKEOVER';

/** Текст для человека — показывается, если отказ всё же всплыл в интерфейсе. */
export const SESSION_TAKEOVER_MESSAGE = 'Сессия обновлена в другой вкладке — обновите страницу';

/**
 * Отказ, которым перехватчик запросов гасит обращение к серверу из вкладки с
 * чужим токеном. Отдельный код нужен, чтобы обработчик ответов не спутал его с
 * сетевым сбоем и не начал переигрывать запрос через резервный шлюз.
 */
export function sessionTakeoverError(): Error {
  const err = new Error(SESSION_TAKEOVER_MESSAGE) as Error & { code: string };
  err.code = SESSION_TAKEOVER_CODE;
  return err;
}

export function isSessionTakeoverError(err: unknown): boolean {
  return (err as { code?: unknown } | null)?.code === SESSION_TAKEOVER_CODE;
}
