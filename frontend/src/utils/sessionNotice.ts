/**
 * ПРИЧИНА ПРИНУДИТЕЛЬНОГО РАЗЛОГИНА — единственный канал, переживающий
 * перезагрузку вкладки (мульти-точки 163).
 *
 * ЗАЧЕМ. Когда у сотрудника снимают доступ к филиалу или филиал архивируют,
 * сервер отвечает 401 «Филиал больше не доступен — войдите заново» на ЛЮБОЙ
 * запрос. Веб гасит такую сессию жёстко — через `window.location.href`
 * (см. api/axios.ts), потому что только полная перезагрузка гарантированно
 * убивает всё, что уже успело отрисоваться с чужими цифрами. Но полная
 * перезагрузка стирает и React-состояние: сказать человеку ПРИЧИНУ на экране
 * входа уже нечем.
 *
 * Без причины мастер посреди смены видит «меня выкинуло», считает это
 * поломкой и звонит владельцу — вместо того чтобы войти в доступный филиал.
 * Поэтому текст сервера кладём в sessionStorage и забираем ровно один раз.
 *
 * ПОЧЕМУ sessionStorage, А НЕ localStorage. Причина относится к ЭТОЙ вкладке и
 * к ЭТОМУ моменту: localStorage показал бы её и в соседней вкладке, где
 * человек спокойно работает, и через неделю на общем компьютере автосервиса.
 * Хранилище может быть недоступно (приватный режим, политика браузера) —
 * поэтому каждый доступ обёрнут в try/catch: не показать причину неприятно,
 * а уронить экран входа исключением недопустимо.
 */
const SESSION_NOTICE_KEY = 'autexa:session-ended-notice';

/** Запомнить причину до перезагрузки на /login. */
export function rememberSessionEndedNotice(message: string): void {
  try {
    sessionStorage.setItem(SESSION_NOTICE_KEY, message);
  } catch {
    // Хранилище недоступно — человек просто не увидит причину.
  }
}

/**
 * Прочитать причину, НЕ стирая её.
 *
 * Почему не «прочитал и сразу забыл»: значение читается в инициализаторе
 * useState провайдера, а React в dev-режиме (StrictMode) вызывает такие
 * инициализаторы ДВАЖДЫ. Стирающее чтение отдало бы причину первому вызову, а
 * второму — уже пустоту, и человек не увидел бы объяснения ровно там, где оно
 * нужно. Стирает её тот, кто ПОКАЗАЛ, — через forgetSessionEndedNotice().
 */
export function peekSessionEndedNotice(): string | null {
  try {
    const value = sessionStorage.getItem(SESSION_NOTICE_KEY);
    return value && value.trim() ? value : null;
  } catch {
    return null;
  }
}

/** Стереть, не показывая: обычный выход из аккаунта причины не имеет. */
export function forgetSessionEndedNotice(): void {
  try {
    sessionStorage.removeItem(SESSION_NOTICE_KEY);
  } catch {
    // См. комментарий выше.
  }
}
