/**
 * ОФЛАЙН-ОЧЕРЕДЬ И СМЕНА ФИЛИАЛА — ЧИСТЫЕ ПРАВИЛА (167-web).
 *
 * ПРОБЛЕМА, РАДИ КОТОРОЙ ЭТОТ МОДУЛЬ. В вебе очередь недоотправленных мутаций
 * живёт не в памяти вкладки, а в Service Worker: IndexedDB `autexa-sw`, стор
 * `autexa-offline-queue`. Записи НЕ хранят Authorization (SW v14: протухший
 * Bearer в базе — это и утечка, и гарантированный 401), поэтому при досылке SW
 * берёт токен у живой вкладки. Отсюда два следствия, каждое из которых стоит
 * денег:
 *
 *   1. если перед сменой филиала очередь СТЕРЕТЬ (как это делает вход), три
 *      пробитых без связи заказ-наряда исчезнут молча;
 *   2. если очередь ОСТАВИТЬ и переключиться, SW дошлёт её уже под токеном
 *      НОВОГО филиала — выручка запишется в чужой автосервис.
 *
 * Мобилка решает это штампом филиала в каждой записи (offlineCheckQueue
 * .stampPendingPoint): там очередь своя, формат наш, и сервер по штампу кладёт
 * чек куда надо. В вебе записи — это сырые HTTP-запросы, и добавить им филиал
 * без правки контракта API нельзя. Поэтому веб-правило жёстче и проще:
 *
 *      ЛИБО ОЧЕРЕДЬ ДОИГРАНА ПОЛНОСТЬЮ — ЛИБО ФИЛИАЛ НЕ МЕНЯЕТСЯ.
 *
 * Доигрываем ДО перевыпуска сессии, пока жив токен ТЕКУЩЕГО филиала: так
 * деньги попадают ровно туда, где их пробили. Не получилось — человек остаётся
 * там же, где был, и читает, что именно произошло. Остаться не в том филиале —
 * неудобство на один клик; увезти чужую выручку — потеря, которую никто не
 * заметит до сверки кассы.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ. Ровно та же причина, что у switchPointFailure.ts:
 * у исхода несколько веток, у каждой свой единственно верный результат, и
 * разбросанные по экрану `if`-ы такую ветвистость не показывают целиком.
 */
import type { OfflineQueueFlush, OfflineQueueState } from './swCache';

/**
 * ИТОГ ПОПЫТКИ ДОИГРАТЬ ОЧЕРЕДЬ ПЕРЕД ПЕРЕКЛЮЧЕНИЕМ.
 *
 * `ok: true` — переключаться МОЖНО: в очереди не осталось ничего, что уехало бы
 * в новый филиал. `ok: false` — остаёмся на месте и объясняем причину.
 */
export type QueueSwitchVerdict =
  | { ok: true; sent: number }
  | {
      ok: false;
      /**
       * • `stuck`    — записи остались (нет связи, сервер не ответил);
       * • `rejected` — сервер отклонил часть записей прямо сейчас: на сервер
       *                они НЕ попали, и человек обязан узнать об этом до, а не
       *                после перехода;
       * • `no-sw`    — вкладкой не управляет Service Worker: доиграть очередь
       *                некому, а значит и гарантии нет;
       * • `timeout`  — SW не ответил вовремя; досылка, возможно, ещё идёт;
       * • `error`    — механизм очереди отказал (IndexedDB недоступна).
       */
      reason: 'stuck' | 'rejected' | 'no-sw' | 'timeout' | 'error';
      /** Сколько записей ждёт отправки (по последнему известному замеру). */
      pending: number;
      /** Сколько записей отклонено ИМЕННО В ЭТОЙ попытке (для `rejected`). */
      rejected: number;
    };

/**
 * Решение по замеру «до» и результату досылки. Чистая функция: решение о том,
 * переключать ли сессию, не должно зависеть ни от порядка рендеров, ни от
 * состояния экрана.
 *
 * ПОРЯДОК ПРОВЕРОК ВАЖЕН. Сначала «доиграли ли вообще» (нет ответа — нет
 * знания), потом остаток очереди (это то, что уедет в чужой филиал), и только
 * потом свежие отказы: они уже не уедут никуда, но это несохранённые деньги.
 */
export function judgeQueueFlush(before: OfflineQueueState, flush: OfflineQueueFlush): QueueSwitchVerdict {
  if (flush.status !== 'flushed') {
    return { ok: false, reason: flush.status, pending: before.pending, rejected: 0 };
  }

  if (flush.pending > 0) {
    return { ok: false, reason: 'stuck', pending: flush.pending, rejected: 0 };
  }

  // Архив отказов вырос — значит сервер отклонил записи в эту самую попытку.
  // Сравниваем с замером «до», а не с нулём: старые отказы могли лежать там
  // неделю, и запрещать из-за них переход навсегда было бы неправдой.
  const rejected = Math.max(0, flush.failed - before.failed);
  if (rejected > 0) {
    return { ok: false, reason: 'rejected', pending: 0, rejected };
  }

  return { ok: true, sent: before.pending };
}

/**
 * ОТКАЗ «сначала разберитесь с очередью». Отдельный класс нужен, чтобы экран не
 * прогнал его через resolveSwitchPointFailure: тот разбирает ответы сервера, и
 * ошибку без HTTP-статуса он объявил бы отсутствием связи — человек искал бы
 * проблему в интернете вместо своих неотправленных чеков.
 */
export class OfflineQueueBlockedError extends Error {
  readonly verdict: Extract<QueueSwitchVerdict, { ok: false }>;

  constructor(verdict: Extract<QueueSwitchVerdict, { ok: false }>) {
    super('Офлайн-очередь не доиграна — филиал не переключён');
    this.name = 'OfflineQueueBlockedError';
    this.verdict = verdict;
  }
}

export function isOfflineQueueBlockedError(err: unknown): err is OfflineQueueBlockedError {
  return err instanceof OfflineQueueBlockedError;
}

// ── Русские числительные ─────────────────────────────────────────────────────
// Текст про пропавшие деньги должен читаться как человеческая речь. «Сервер
// отклонил 1 операция» превращает предупреждение в машинный лог, а такому не
// верят и не следуют.

/** Особая группа 11–14: у неё всегда форма множественного числа. */
function isTeen(count: number): boolean {
  const tail = count % 100;
  return tail >= 11 && tail <= 14;
}

/** Именительный: «1 операция» · «2 операции» · «5 операций». */
function operationNounRu(count: number): string {
  const last = count % 10;
  if (isTeen(count)) return 'операций';
  if (last === 1) return 'операция';
  if (last >= 2 && last <= 4) return 'операции';
  return 'операций';
}

/** Винительный (после глагола): «отклонил 1 операцию · 2 операции · 5 операций». */
function operationNounAccusative(count: number): string {
  const last = count % 10;
  if (isTeen(count)) return 'операций';
  if (last === 1) return 'операцию';
  if (last >= 2 && last <= 4) return 'операции';
  return 'операций';
}

/** «1 неотправленная операция» · «3 неотправленные операции» · «5 неотправленных операций». */
function unsentPhrase(count: number): string {
  const last = count % 10;
  const adjective = isTeen(count)
    ? 'неотправленных'
    : last === 1
      ? 'неотправленная'
      : last >= 2 && last <= 4
        ? 'неотправленные'
        : 'неотправленных';
  return `${count} ${adjective} ${operationNounRu(count)}`;
}

/** «осталась 1 операция» · «осталось 3 операции» · «осталось 5 операций». */
function remainedPhrase(count: number): string {
  const verb = count % 10 === 1 && !isTeen(count) ? 'осталась' : 'осталось';
  return `${verb} ${count} ${operationNounRu(count)}`;
}

function pointPhrase(name: string | null): string {
  return name ? `«${name}»` : 'текущий филиал';
}

/**
 * ЧТО ЧЕЛОВЕК ЧИТАЕТ ПЕРЕД ПЕРЕКЛЮЧЕНИЕМ, ЕСЛИ В ОЧЕРЕДИ ЕСТЬ НЕОТПРАВЛЕННОЕ.
 *
 * Текст обязан ответить на три вопроса, и ровно в этом порядке: что вообще
 * лежит на устройстве, куда это уйдёт и что будет, если не уйдёт. Последнее —
 * не вежливость, а главное обещание: человек должен заранее знать, что при
 * неудаче он останется в своём филиале, а не окажется неизвестно где с
 * неизвестно чем.
 *
 * Пустая строка = очередь пуста: диалога быть не должно вовсе, переключение
 * делается сразу («просто нажал — перешёл»).
 */
export function pendingQueueSwitchNotice(
  pending: number,
  currentPointName: string | null,
  targetPointName: string,
): string {
  if (pending <= 0) return '';
  const here = pointPhrase(currentPointName);
  return (
    `На этом устройстве ${unsentPhrase(pending)} — они были сделаны без связи и ещё не ушли на сервер. ` +
    `Сейчас отправим их в ${here}, и только после этого перейдём в «${targetPointName}». ` +
    `Если отправить не получится, вы останетесь в ${here} — ничего не потеряется.`
  );
}

/**
 * ПОЧЕМУ ПЕРЕХОД НЕ СОСТОЯЛСЯ. Показывается на экране (не тостом): это не
 * уведомление, а инструкция, и она должна дождаться, пока её прочитают.
 *
 * В каждой строке — и что с деньгами, и что делать дальше. «Не удалось
 * перейти» без второй половины заставляет человека жать кнопку по кругу.
 */
export function queueBlockMessage(
  verdict: Extract<QueueSwitchVerdict, { ok: false }>,
  currentPointName: string | null,
): string {
  const here = pointPhrase(currentPointName);

  switch (verdict.reason) {
    case 'stuck':
      return (
        `Не удалось отправить сохранённое: ${remainedPhrase(verdict.pending)}. ` +
        `Вы остались в ${here} — переход отменён, чтобы эти записи не ушли в другой филиал. ` +
        `Данные сохранены на этом устройстве. Проверьте связь и повторите переход.`
      );
    case 'rejected':
      return (
        `Сервер отклонил ${verdict.rejected} ${operationNounAccusative(verdict.rejected)}: на сервер эти данные не попали. ` +
        `Вы остались в ${here}. Проверьте их и введите заново, затем повторите переход.`
      );
    case 'no-sw':
      return (
        `Фоновая отправка сейчас недоступна, поэтому сохранённое отправить не удалось. ` +
        `Вы остались в ${here}, данные на устройстве целы. Обновите страницу (F5) и повторите переход.`
      );
    case 'timeout':
      return (
        `Отправка сохранённого не завершилась за отведённое время и, возможно, ещё идёт. ` +
        `Вы остались в ${here} — переход отменён, чтобы записи не ушли в другой филиал. ` +
        `Подождите минуту и повторите.`
      );
    case 'error':
    default:
      return (
        `Не удалось проверить, всё ли сохранённое отправлено, поэтому переход отменён — вы остались в ${here}. ` +
        `Обновите страницу и повторите; если повторится, не меняйте филиал и сообщите в поддержку.`
      );
  }
}

/**
 * ДОПОЛНЕНИЕ К ДИАЛОГУ «ВЫЙТИ И ВОЙТИ» (путь сотрудника, у которого нет права
 * на мгновенный переход). Выход из аккаунта очередь СТИРАЕТ осознанно — за
 * клавиатуру может сесть другой человек, и досылка под его токеном была бы
 * записью в чужую кассу. Но молчать об этом нельзя: человек должен решать,
 * зная, что именно исчезнет.
 */
export function pendingQueueLogoutWarning(pending: number): string {
  if (pending <= 0) return '';
  return (
    ` Важно: на этом устройстве ${unsentPhrase(pending)}, сделанные без связи, — выход из аккаунта их удалит. ` +
    `Дождитесь связи и убедитесь, что они отправлены, прежде чем выходить.`
  );
}
