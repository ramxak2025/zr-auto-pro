export interface HeroContent {
  badge: string;
  title: string;
  subtitle: string;
  bullets: [string, string, string];
}

export type RoleKey = 'owner' | 'admin' | 'master';

export interface RolePersona {
  key: RoleKey;
  title: string;
  /** Боль без продукта — узнаваемая, из жизни сервиса. */
  pains: string[];
  /** Что человек получает с Autexa. */
  gains: string[];
}

export interface Capability {
  title: string;
  text: string;
}

export interface FaqItem {
  q: string;
  a: string;
}

export interface RoleBenefits {
  owner: string;
  admin?: string;
  master?: string;
}

export interface FeatureDetail {
  heroTitle: string;
  heroSubtitle: string;
  /** Как живётся без продукта: тетрадка, Excel, споры. */
  pains: string[];
  /** Каждая capability — реальная возможность из кода приложения. */
  capabilities: Capability[];
  roleBenefits: RoleBenefits;
  faq: FaqItem[];
  /** Мостик к действию в конце страницы раздела. */
  ctaText: string;
}

export interface FeatureSection {
  slug: string;
  /** Имя иконки lucide-react, например 'Receipt'. */
  icon: string;
  title: string;
  /** Одна продающая строка для плитки на главной. */
  tagline: string;
  /** 2–3 предложения для карточки раздела. */
  summary: string;
  detail: FeatureDetail;
}

export interface CtaSectionContent {
  title: string;
  subtitle: string;
  /** Риск-реверс: снимаем страх решения. */
  riskReversal: string;
  whatsappLabel: string;
  telegramLabel: string;
  note: string;
}

export interface StorePlatform {
  /** Имя иконки lucide-react. */
  icon: string;
  title: string;
  text: string;
}

export interface StoreBadge {
  /** Имя иконки lucide-react. */
  icon: string;
  store: string;
  note: string;
}

export interface StoreSectionContent {
  title: string;
  subtitle: string;
  platforms: StorePlatform[];
  badges: StoreBadge[];
  supportInstallLabel: string;
  syncNote: string;
}

/** Значение ячейки сравнения тарифов: ✓ (true) / — (false) / текст («до 10», «1000 мин/мес»). */
export type PlanCellValue = boolean | string;

export interface PricingPlan {
  key: string;
  name: string;
  /** Цена в месяц, уже отформатированная: '1 000'. */
  price: string;
  /** Подпись про размер команды: '1 сотрудник' / 'до 10 сотрудников'. */
  employees: string;
  /** Одна строка сути тарифа. */
  description: string;
  /** «Что входит» — главные пункты карточки (только реальные возможности плана). */
  includes: string[];
  /** Рекомендуемый тариф: выделенная карточка + бейдж. */
  highlighted?: boolean;
  badge?: string;
}

export interface PricingRow {
  feature: string;
  /** Значения по тарифам — строго в порядке pricing.plans. */
  values: [PlanCellValue, PlanCellValue, PlanCellValue];
}

export interface ImplementationOffer {
  title: string;
  price: string;
  priceNote: string;
  duration: string;
  text: string;
  includes: string[];
  ctaLabel: string;
}

export interface PricingContent {
  title: string;
  subtitle: string;
  /** Честная подпись под карточками — снимает страх скрытых платежей. */
  honestyNote: string;
  plans: PricingPlan[];
  implementation: ImplementationOffer;
  comparisonTitle: string;
  commonLabel: string;
  /** Строки различий — идут СВЕРХУ таблицы сравнения (сначала разница, потом общее). */
  differences: PricingRow[];
  /** Возможности, входящие во все три тарифа. */
  commonFeatures: string[];
  /** Короткие имена планов для мини-чипов мобильного сравнения. */
  planShortNames: [string, string, string];
  /** Легенда мини-чипов («Л — Личный …»). */
  planShortLegend: string;
}

