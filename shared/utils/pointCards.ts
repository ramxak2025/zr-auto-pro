/**
 * КАРТОЧКИ РАЗДЕЛА «ФИЛИАЛЫ» — ЧИСТОЕ ПРАВИЛО СБОРКИ СПИСКА (мульти-точки
 * 156/160/161/163).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Владелец складывает карточки филиалов и обязан
 * получить ту же цифру, что видит на главной. Пока клиент строил список по
 * GET /points (это ТОЛЬКО живые точки) и лишь подтягивал к ним сводку по id,
 * деньги ЗАКРЫТОГО филиала оставались в итогах тенанта, а карточки для них не
 * существовало: сумма карточек не сходилась с итогом сети, и владелец читал
 * это как пропажу денег. Сервер уже чинен — GET /points/summary отдаёт и
 * закрытые точки (PointSummary.isArchived), когда в показанном периоде у них
 * есть деньги или работа. Значит источник списка карточек — СВОДКА, а живой
 * список остаётся источником подробностей (адрес, состав) и права войти.
 *
 * ПОЧЕМУ В shared. Правило должно совпадать в мобилке и в вебе ДОСЛОВНО:
 * расхождение здесь — это два разных ответа на вопрос «сколько заработала
 * сеть», данных одному человеку на двух экранах. Копии в двух файлах уже
 * разъезжались (см. usePoints), поэтому правило живёт здесь в одном
 * экземпляре и покрыто юнит-тестом (mobile/src/utils/__tests__/pointCards.test.ts).
 */
import type { PointSummary, TenantPoint } from '../types';

/**
 * Одна карточка раздела. Собрана из двух источников: живой записи точки
 * (GET /points) и её строки в сводке (GET /points/summary). Любой из них
 * может отсутствовать:
 *   • нет `summary` — у человека нет права `financial_reports`, сводку мы
 *     даже не запрашиваем (карточка рисует прочерки вместо денег);
 *   • нет `point` — филиал ЗАКРЫТ и в живом списке его уже нет, карточка
 *     существует только ради денег, оставшихся в итогах периода.
 */
export interface PointCardRow {
  pointId: string;
  name: string;
  /** Адрес известен только по живой записи: у закрытого филиала его нет. */
  address: string | null;
  /** ОСНОВНОЙ сервис тенанта (tenant_points.is_main), а не филиал. */
  isMain: boolean;
  /**
   * ФИЛИАЛ ЗАКРЫТ. Клиент обязан подписать карточку «Закрыт» и НЕ предлагать
   * в неё войти: филиал заархивирован, и сервер туда не пустит.
   */
  isArchived: boolean;
  /** Живая запись из GET /points. null — филиала в живом списке уже нет. */
  point: TenantPoint | null;
  /** Строка сводки. null — денег человек не видит либо ответ ещё не пришёл. */
  summary: PointSummary | null;
}

/**
 * Собрать карточки раздела «Филиалы».
 *
 * ПОРЯДОК: действующие филиалы первыми и РОВНО в том порядке, в каком их
 * отдал сервер в GET /points (основной сервис первым — на него завязана
 * отдельная секция экрана), закрытые — в хвосте в порядке сводки. Сортировка
 * устойчивая: внутри группы порядок источника не меняется.
 *
 * ПРИЗНАК ЗАКРЫТОСТИ берётся из сводки (`isArchived`) — это ответ сервера на
 * вопрос «закрыт ли филиал в показанном периоде». Если строки сводки нет
 * (человек без права на деньги), падаем на `TenantPoint.isActive`: GET /points
 * отдаёт помимо живых точек ещё и точку ТЕКУЩЕЙ СЕССИИ, а её могли закрыть
 * уже после входа.
 *
 * ТЕНАНТ, У КОТОРОГО НИЧЕГО НЕ ЗАКРЫТО, НЕ ЗАМЕЧАЕТ ЭТОЙ ФУНКЦИИ ВОВСЕ:
 * на входе живой список и сводка по тем же точкам — на выходе тот же список
 * в том же порядке.
 */
export function buildPointCardRows(input: {
  /** Живые точки тенанта из GET /points (уже отсортированы сервером). */
  points: TenantPoint[];
  /** Строки GET /points/summary. Пусто = сводки нет (нет права или не пришла). */
  summary: PointSummary[];
}): PointCardRow[] {
  const { points, summary } = input;

  const summaryById = new Map<string, PointSummary>();
  for (const s of summary) summaryById.set(s.pointId, s);

  const rows: PointCardRow[] = points.map((p) => {
    const s = summaryById.get(p.id) ?? null;
    return {
      pointId: p.id,
      name: p.name,
      address: p.address ?? null,
      isMain: p.isMain,
      isArchived: s ? s.isArchived : p.isActive === false,
      point: p,
      summary: s,
    };
  });

  // Закрытые филиалы, которых в живом списке уже нет, — это и есть та самая
  // недостающая часть суммы. Сервер прислал их ТОЛЬКО потому, что в периоде у
  // них есть деньги или работа; молча выбросить их — вернуть расхождение.
  const livePointIds = new Set(points.map((p) => p.id));
  for (const s of summary) {
    if (livePointIds.has(s.pointId)) continue;
    rows.push({
      pointId: s.pointId,
      name: s.name,
      address: null,
      isMain: s.isMain,
      isArchived: s.isArchived,
      point: null,
      summary: s,
    });
  }

  // Действующие первыми, закрытые в хвост. Именно в этом порядке владелец
  // складывает карточки: сначала то, что работает, потом остаток периода.
  //
  // concat, а НЕ [...live, ...archived]: spread заставляет babel подтянуть
  // хелпер из @babel/runtime, а из каталога shared/ (у него нет своих
  // node_modules) jest его не резолвит — юнит-тест правила просто перестаёт
  // запускаться. Соседний plate.ts живёт по тому же ограничению.
  const live = rows.filter((r) => !r.isArchived);
  const archived = rows.filter((r) => r.isArchived);
  return live.concat(archived);
}
