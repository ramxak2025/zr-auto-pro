/**
 * Разбор ОТКАЗОВ СЕРВЕРА — один на веб и мобилку.
 *
 * ЗАЧЕМ ОБЩИЙ МОДУЛЬ. Форма ошибки задаётся сервером (NestJS-фильтр
 * исключений), и оба клиента обязаны читать её ОДИНАКОВО. Пока разбор жил
 * копиями по экранам, половина из них глотала причину («Ошибка при создании
 * клиента» вместо «этот номер уже занят»), а половина — разъезжалась в
 * деталях. Здесь же живут два отказа, у которых есть ОСМЫСЛЕННОЕ ДЕЙСТВИЕ, а
 * не только текст:
 *
 *   • 401 «Филиал больше не доступен — войдите заново» (163, JwtStrategy) —
 *     сессия обесточена: филиал заархивировали или у сотрудника сняли доступ.
 *     Правильная реакция одна: сказать это человеческим текстом и увести на
 *     вход. Подставить другой филиал молча НЕЛЬЗЯ — он начнёт пробивать чеки
 *     не в том автосервисе, не заметив подмены;
 *   • 409 CLIENT_PHONE_EXISTS_OTHER_POINT — номер занят карточкой чужого
 *     филиала. Навигировать некуда: карточки не видно, id сервер не отдаёт.
 *
 * ПОЧЕМУ РАСПОЗНАЁМ ПО ТЕКСТУ, А НЕ ПО КОДУ. Форма ошибки задана сервером и
 * зафиксирована его тестами: HTTP 401 + `{ message: '…' }`. Заводить второй
 * контракт (машинный `code`) значило бы выкатывать сервер и клиенты синхронно
 * и до тех пор показывать старым сборкам молчаливый разлогин. Сравнение —
 * по ПОЛНОЙ строке, поэтому чужой отказ со словом «филиал» сюда не попадёт.
 *
 * Модуль чистый (без axios и React) — работает и в вебе, и в мобилке, и в
 * юнит-тестах.
 */

/**
 * Сообщения сервера (163), после которых сессия мертва и нужен НОВЫЙ ВХОД.
 * Один в один с backend/src/auth/jwt.strategy.ts — расхождение строки означало
 * бы молчаливый разлогин без объяснения.
 */
export const SESSION_POINT_LOST_MESSAGE = 'Филиал больше не доступен — войдите заново';
/** Промежуточным токеном выбора филиала постучались в обычную ручку (баг клиента). */
export const SESSION_POINT_NOT_CHOSEN_MESSAGE = 'Выберите филиал, чтобы продолжить';
/**
 * Пароль сменили (сам сотрудник или владелец сбросил) — ВСЕ выданные до этого
 * токены мертвы (165). Тот же класс отказа, что и потеря филиала: держать
 * мёртвый токен нельзя, а человеку нужно объяснить, почему его выкинуло, —
 * иначе он решит, что приложение сломалось, и не догадается войти с новым
 * паролем.
 */
export const SESSION_PASSWORD_CHANGED_MESSAGE = 'Пароль изменён — войдите заново';
/**
 * Сотруднику не доступен НИ ОДИН живой филиал (165) — например, его
 * единственный филиал закрыли. Работать без филиала у тенанта С филиалами
 * нельзя: денежные записи такой сессии не попали бы ни в один филиальный срез.
 * Выход один — руководитель назначает доступ, после чего человек входит заново.
 */
export const SESSION_NO_POINT_ACCESS_MESSAGE =
  'Вам не назначен ни один действующий филиал — обратитесь к руководителю';

/** Код 409, когда номер занят карточкой ДРУГОГО филиала (см. shared/types). */
export const CLIENT_PHONE_OTHER_POINT_CODE = 'CLIENT_PHONE_EXISTS_OTHER_POINT';

/** Тело ошибки, как его отдаёт NestJS-фильтр исключений. */
interface ApiErrorBody {
  message?: string | string[];
  error?: string;
  code?: string;
}

interface ApiErrorLike {
  response?: { status?: number; data?: ApiErrorBody | string };
  message?: string;
}

/** Тело ответа, если ошибка похожа на отказ HTTP-клиента; иначе null. */
function errorBody(err: unknown): ApiErrorBody | null {
  const data = (err as ApiErrorLike | null)?.response?.data;
  return data && typeof data === 'object' ? data : null;
}

/** HTTP-статус отказа или null (сетевой сбой — статуса нет). */
export function apiErrorStatus(err: unknown): number | null {
  const status = (err as ApiErrorLike | null)?.response?.status;
  return typeof status === 'number' ? status : null;
}

/**
 * Текст ошибки от сервера ДОСЛОВНО. Массив (class-validator отдаёт список
 * нарушений) склеиваем переводами строк, чтобы владелец увидел все причины,
 * а не первую. null — сервер текста не дал, вызывающий подставляет свой.
 */
export function apiErrorMessage(err: unknown): string | null {
  const body = errorBody(err);
  const msg = body?.message;
  if (typeof msg === 'string' && msg.trim()) return msg;
  if (Array.isArray(msg)) {
    const joined = msg.filter((m) => typeof m === 'string' && m.trim()).join('\n');
    if (joined) return joined;
  }
  if (typeof body?.error === 'string' && body.error.trim()) return body.error;
  return null;
}

/**
 * СЕССИЯ ПОТЕРЯЛА ФИЛИАЛ (163): 401, после которого единственный выход — войти
 * заново. Возвращает ТЕКСТ сервера (его и показываем на экране входа) либо
 * null, если это обычное истечение токена или чужая ошибка.
 *
 * Зачем отличать от прочих 401. Разлогин по истечению токена человеку понятен
 * («давно не заходил»), а вот выброшенный из смены мастер обязан узнать
 * ПРИЧИНУ: доступ к филиалу сняли или филиал закрыли. Без текста он видит
 * «меня выкинуло» и звонит владельцу, вместо того чтобы войти в другой филиал.
 *
 * Статус проверяем мягко: ответа нет вовсе (офлайн) → проверять нечего.
 */
export function sessionPointLostMessage(err: unknown): string | null {
  if (apiErrorStatus(err) !== 401) return null;
  const message = apiErrorMessage(err);
  if (message === SESSION_POINT_LOST_MESSAGE) return message;
  if (message === SESSION_POINT_NOT_CHOSEN_MESSAGE) return message;
  // 165 — те же «сессия кончилась насовсем, войдите заново»: смена пароля
  // гасит все прежние токены, а закрытие последнего доступного филиала
  // оставляет сотрудника без места работы. Реакция клиента одинакова с
  // потерей филиала: показать текст сервера и увести на вход.
  if (message === SESSION_PASSWORD_CHANGED_MESSAGE) return message;
  if (message === SESSION_NO_POINT_ACCESS_MESSAGE) return message;
  return null;
}

/**
 * 409 «номер занят карточкой другого филиала». Карточки владельца НЕТ в
 * ответе намеренно (ни имени, ни id — иначе мастер узнавал бы клиента чужого
 * филиала), поэтому клиент обязан показать текст и НЕ пытаться никуда
 * навигировать: «Перейти к клиенту» привело бы в 404.
 */
export function otherPointPhoneConflictMessage(err: unknown): string | null {
  if (apiErrorStatus(err) !== 409) return null;
  const body = errorBody(err);
  if (body?.code !== CLIENT_PHONE_OTHER_POINT_CODE) return null;
  return apiErrorMessage(err) ?? 'Этот номер уже занят карточкой другого филиала';
}
